"""Собирает desktop/plugin.js (Hermes Desktop) из dashboard/dist/index.js + style.css.

Hermes Desktop не грузит веб-вкладки: ему нужен ESM-файл, который импортирует
только react и @hermes/plugin-sdk и экспортирует HermesPlugin. Код страницы
общий: index.js — фабрика (SDK, onReady); здесь ей подаётся SDK, у которого
fetchJSON идёт через ctx.rest (namespace /api/plugins/yadro-guard).
Запуск: python tools/build_desktop_plugin.py   (--check: только сверить)
"""
import json
import sys
from pathlib import Path

ПЛАГИН = Path(__file__).resolve().parents[1] / "integrations" / "hermes" / "yadro-guard"
НАЧАЛО = "(function (SDK, onReady) {"
КОНЕЦ = "})(window.__HERMES_PLUGIN_SDK__,"


def собрать() -> str:
    js = (ПЛАГИН / "dashboard" / "dist" / "index.js").read_text(encoding="utf-8")
    css = (ПЛАГИН / "dashboard" / "dist" / "style.css").read_text(encoding="utf-8")
    i, j = js.index(НАЧАЛО), js.rindex(КОНЕЦ)
    фабрика = "function (SDK, onReady) {" + js[i + len(НАЧАЛО):j] + "}"
    return (
        "// GENERATED by tools/build_desktop_plugin.py from dashboard/dist — do not edit.\n"
        'import * as React from "react";\n'
        'import { host } from "@hermes/plugin-sdk";\n\n'
        f"const CSS = {json.dumps(css)};\n"
        'const API = "/api/plugins/yadro-guard";\n'
        "let rest = null;\n"
        "let GuardPage = null;\n\n"
        "function fetchJSON(url, init) {\n"
        "  if (!rest) return Promise.reject(new Error(\"Guard is not registered yet\"));\n"
        "  if (url !== API && url.indexOf(API + \"/\") !== 0 && url.indexOf(API + \"?\") !== 0)\n"
        "    return Promise.reject(new Error(\"Guard cannot access \" + url));\n"
        "  const opts = {};\n"
        "  if (init && init.method) opts.method = init.method;\n"
        "  if (init && init.body != null) opts.body = typeof init.body === \"string\" ? JSON.parse(init.body) : init.body;\n"
        "  return rest(url.slice(API.length) || \"/\", opts);\n"
        "}\n\n"
        f"const makeGuardPage = {фабрика};\n"
        "makeGuardPage({ React: React, fetchJSON: fetchJSON }, function (Page) { GuardPage = Page; });\n\n"
        "function DesktopGuardPage() {\n"
        "  return React.createElement(\"div\", { style: { height: \"100%\" } },\n"
        "    React.createElement(\"style\", null, CSS), React.createElement(GuardPage));\n"
        "}\n\n"
        "export default {\n"
        '  id: "yadro-guard",\n'
        '  name: "Guard",\n'
        '  description: "Yadro Guard: live leak blocking, exposure scan, code check and vault. Offline.",\n'
        "  defaultEnabled: true,\n"
        "  register(ctx) {\n"
        "    rest = ctx.rest;\n"
        "    ctx.registerMany([\n"
        '      { id: "page", area: "routes", title: "Guard", data: { path: "/guard" }, render: function () { return React.createElement(DesktopGuardPage); } },\n'
        '      { id: "nav", area: "sidebar.nav", order: -900, data: { path: "/guard", label: "Guard", codicon: "shield" } },\n'
        '      { id: "open", area: "palette", data: { id: "guard.open", label: "Open Yadro Guard", keywords: ["guard", "security", "secrets"], run: function () { host.navigate("/guard"); } } }\n'
        "    ]);\n"
        "  }\n"
        "};\n"
    )


def main() -> int:
    цель = ПЛАГИН / "desktop" / "plugin.js"
    текст = собрать()
    if "--check" in sys.argv:
        ok = цель.exists() and цель.read_text(encoding="utf-8") == текст
        print("ok" if ok else "desktop/plugin.js устарел: python tools/build_desktop_plugin.py")
        return 0 if ok else 1
    цель.parent.mkdir(exist_ok=True)
    цель.write_text(текст, encoding="utf-8", newline="\n")
    print(f"written {цель}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
