class БазаПоведенческихТестов(unittest.TestCase):
    """Общие утверждения: компиляция обязана либо пройти, либо отсечь утечку."""

    def _компилируется(self, код, контекст):
        """Код безопасен и обязан компилироваться (иначе — ложная блокировка)."""
        try:
            компилировать(код)
        except ЭтическаяОшибка as ошибка:
            self.fail(
                f"{контекст}: анализатор ЛОЖНО отсекает безопасный код "
                f"[{ошибка.код}] {ошибка}"
            )

    def _отсекается(self, код, контекст, код_ошибки=None, метки=()):
        """Код утекает и обязан быть отсечён этическим анализатором."""
        try:
            компилировать(код)
        except ЭтическаяОшибка as ошибка:
            if код_ошибки:
                self.assertEqual(
                    ошибка.код, код_ошибки,
                    f"{контекст}: ожидался код {код_ошибки}, получен {ошибка.код}.")
            for метка in метки:
                self.assertIn(метка, str(ошибка),
                              f"{контекст}: в диагностике нет метки '{метка}'.")
            return ошибка
        self.fail(
            f"{контекст}: утечка НЕ отсечена — компилятор выдал LLVM IR. "
            f"Это недостающая блокировка PATCH 4-6."
        )



