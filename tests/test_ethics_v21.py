import unittest
from src.main import компилировать
from src.этика import ЭтическаяОшибка, ЭтическийАнализатор
from src.лексер import Лексер
from src.синтаксис import Парсер


class ТестыЭтикиV21(unittest.TestCase):
    def test_неподходящий_санитайзер_не_снимает_финансовую_метку(self):
        код = """
        функ старт() требует [ДоступСети] {
          пусть карта = платеж.карта()
          пусть неверно = анонимизировать(карта)
          вернуть сеть.отправить(неверно)
        }
        """
        with self.assertRaisesRegex(ЭтическаяОшибка, "Финансы"):
            компилировать(код)

    def test_разрешенный_санитайзер_снимает_финансовую_метку(self):
        код = """
        функ старт() требует [ДоступСети] {
          пусть карта = платеж.карта()
          пусть безопасно = зашифровать(карта)
          вернуть сеть.отправить(безопасно)
        }
        """
        компилировать(код)

    def test_сводка_возврата_сохраняет_конкретную_метку(self):
        код = """
        функ прочитать_карту() { вернуть платеж.карта() }
        функ старт() требует [ДоступСети] { вернуть сеть.отправить(прочитать_карту()) }
        """
        with self.assertRaisesRegex(ЭтическаяОшибка, "Финансы"):
            компилировать(код)

    def test_возврат_сохраняет_несколько_меток(self):
        код = """
        функ объединить(а, б) { вернуть а + б }
        функ старт() требует [ДоступСети] {
          пусть смесь = объединить(пользователь.данные(), среда.секрет())
          вернуть сеть.отправить(смесь)
        }
        """
        with self.assertRaises(ЭтическаяОшибка) as ошибка:
            компилировать(код)
        self.assertIn("ПДн", str(ошибка.exception))
        self.assertIn("УчетныеДанные", str(ошибка.exception))

    def test_санитизация_попадает_в_аудит(self):
        код = "функ старт() { пусть х = платеж.карта() пусть у = зашифровать(х) вернуть у }"
        ast = Парсер(Лексер(код).токены()).разобрать()
        анализатор = ЭтическийАнализатор()
        анализатор.проверить(ast)
        self.assertTrue(any(запись.статус == "САНИТАЙЗ" and запись.метка == "Финансы"
                            for запись in анализатор.аудит_трейл))

    def test_зарезервированный_символ_нельзя_подменить(self):
        код = "функ анонимизировать(х) { вернуть 0 } функ старт() { вернуть анонимизировать(пользователь.данные()) }"
        with self.assertRaisesRegex(ЭтическаяОшибка, "Зарезервированный символ"):
            компилировать(код)


if __name__ == "__main__":
    unittest.main()
