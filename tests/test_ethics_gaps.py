# -*- coding: utf-8 -*-
"""Поведенческие регрессии на утечки issue #47 (control-flow aware).

Раньше существовал только `test_patches_quick.py`, который искал строки в
исходнике (`"| pc_метки" in source`), а не поведение. Эти тесты проверяют
РЕАЛЬНОЕ поведение компилятора: каждая дыра обязана теперь отсекаться.

Дыры (из AUDIT_REPORT §2.2):
  1. печать(среда.секрет())            — печать как выводной сток (PATCH 1)
  2. если с { х = 1 } -> сеть(х)       — неявный поток через присваивание (PATCH 2)
  3. helper: если флаг {вернуть 1}     — неявный поток через возврат (PATCH 3)
"""
import unittest

from src.main import компилировать
from src.этика import ЭтическаяОшибка


class ТестыДырокЭтики(unittest.TestCase):
    def test_печать_утечка_секрета_блок(self):
        # PATCH 1: печать — выводной сток; секрет в печать = утечка.
        код = "функ старт() { печать(среда.секрет()) }"
        with self.assertRaisesRegex(ЭтическаяОшибка, "УчетныеДанные"):
            компилировать(код)

    def test_неявный_поток_через_присваивание_блок(self):
        # PATCH 2: переменная, присвоенная под чувствительным условием, заражается.
        код = (
            "функ старт() требует [ДоступСети] {\n"
            "  пусть х = 0\n"
            "  если среда.секрет() { х = 1 }\n"
            "  вернуть сеть.отправить(х)\n"
            "}"
        )
        with self.assertRaisesRegex(ЭтическаяОшибка, "УчетныеДанные"):
            компилировать(код)

    def test_неявный_поток_через_возврат_хелпера_блок(self):
        # PATCH 3: возврат под чувствительным условием переносит управляющий контекст.
        код = (
            "функ helper(флаг) { если флаг { вернуть 1 } вернуть 0 }\n"
            "функ старт() требует [ДоступСети] {\n"
            "  пусть с = среда.секрет()\n"
            "  вернуть сеть.отправить(helper(с))\n"
            "}"
        )
        with self.assertRaises(ЭтическаяОшибка):
            компилировать(код)

    # --- контроль: базовое поведение НЕ регрессирует ---

    def test_печать_константы_не_требует_мандата(self):
        # печать(1) и печать("строка") обязаны компилироваться без мандата.
        компилировать("функ старт() { печать(1) }")
        компилировать('функ старт() { печать("привет") вернуть 0 }')

    def test_прямая_утечка_все_еще_блок(self):
        код = "функ старт() требует [ДоступСети] { вернуть сеть.отправить(пользователь.данные()) }"
        with self.assertRaisesRegex(ЭтическаяОшибка, "ПДн"):
            компилировать(код)

    def test_разрешенный_санитайзер_проходит(self):
        код = (
            "функ старт() требует [ДоступСети] {\n"
            "  пусть карта = платеж.карта()\n"
            "  пусть безопасно = зашифровать(карта)\n"
            "  вернуть сеть.отправить(безопасно)\n"
            "}"
        )
        компилировать(код)

    def test_цикл_фикспойнт_все_еще_ловится(self):
        # Санитайзер внутри цикла, который может не выполниться: заражение остаётся.
        код = (
            "функ слить() требует [ДоступСети] {\n"
            "  пусть данные = пользователь.данные()\n"
            "  пусть и = 0\n"
            "  пока и < 0 { данные = анонимизировать(данные) и = и + 1 }\n"
            "  вернуть сеть.отправить(данные)\n"
            "}\n"
            "функ старт() { вернуть 0 }"
        )
        with self.assertRaisesRegex(ЭтическаяОшибка, "ПДн"):
            компилировать(код)

    def test_межпроцедурная_утечка_параметра_все_еще_блок(self):
        код = (
            "функ слить_наружу(данные) требует [ДоступСети] { вернуть сеть.отправить(данные) }\n"
            "функ главная() требует [ДоступСети] {\n"
            "  пусть тайна = пользователь.данные()\n"
            "  вернуть слить_наружу(тайна)\n"
            "}\n"
            "функ старт() { вернуть 0 }"
        )
        with self.assertRaises(ЭтическаяОшибка):
            компилировать(код)


if __name__ == "__main__":
    unittest.main()
