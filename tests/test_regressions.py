import unittest

from src.main import компилировать, ОшибкаСемантики
from src.этика import ЭтическаяОшибка


class РегрессионныеТестыКомпилятора(unittest.TestCase):
    def test_повторная_функция_отклоняется(self):
        код = "функ тест() { вернуть 1 } функ тест() { вернуть 2 } функ старт() { вернуть 0 }"
        with self.assertRaisesRegex(ОшибкаСемантики, "объявлена повторно"):
            компилировать(код)

    def test_арность_встроенных_функций(self):
        with self.assertRaisesRegex(ОшибкаСемантики, "печать.*ожидает 1"):
            компилировать("функ старт() { вернуть печать() }")
        with self.assertRaisesRegex(ОшибкаСемантики, "анонимизировать.*ожидает 1"):
            компилировать("функ старт() { вернуть анонимизировать() }")

    def test_деление_на_константный_ноль(self):
        with self.assertRaisesRegex(ОшибкаСемантики, "Деление на ноль"):
            компилировать("функ старт() { вернуть 10 / (3 - 3) }")

    def test_переполнение_знакового_деления(self):
        код = "функ старт() { вернуть (0 - 9223372036854775807 - 1) / (0 - 1) }"
        with self.assertRaisesRegex(ОшибкаСемантики, "Переполнение знакового деления"):
            компилировать(код)

    def test_явная_утечка_падает_по_верной_причине(self):
        код = """
        функ старт() требует [ДоступСети] {
            пусть секрет = пользователь.данные()
            вернуть сеть.отправить(секрет)
        }
        """
        with self.assertRaisesRegex(ЭтическаяОшибка, "Утечка данных"):
            компилировать(код)

    def test_неявная_утечка_падает_по_верной_причине(self):
        код = """
        функ старт() требует [ДоступСети] {
            пусть секрет = пользователь.данные()
            если секрет > 0 { сеть.отправить(1) }
            вернуть 0
        }
        """
        with self.assertRaisesRegex(ЭтическаяОшибка, "Неявный информационный поток"):
            компилировать(код)

    def test_санитизированный_поток_компилируется(self):
        код = """
        функ старт() требует [ДоступСети] {
            пусть секрет = пользователь.данные()
            пусть чисто = анонимизировать(секрет)
            вернуть сеть.отправить(чисто)
        }
        """
        self.assertIn("define", компилировать(код))


if __name__ == "__main__":
    unittest.main()
