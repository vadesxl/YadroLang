import unittest
from src.main import компилировать
from src.этика import ЭтическаяОшибка


class ТестыФикспойнтаПотока(unittest.TestCase):
    def test_состояние_цикла_с_нулём_итераций_сливается(self):
        код = """
        функ старт() требует [ДоступСети] {
          пусть значение = 0
          пока значение { значение = пользователь.данные() }
          вернуть сеть.отправить(значение)
        }
        """
        with self.assertRaisesRegex(ЭтическаяОшибка, "ПДн"):
            компилировать(код)

    def test_состояние_ветки_сливается_после_если(self):
        код = """
        функ старт() требует [ДоступСети] {
          пусть значение = 0
          если 1 { значение = среда.секрет() }
          вернуть сеть.отправить(значение)
        }
        """
        with self.assertRaisesRegex(ЭтическаяОшибка, "УчетныеДанные"):
            компилировать(код)


if __name__ == "__main__":
    unittest.main()
