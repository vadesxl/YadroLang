# -*- coding: utf-8 -*-
"""Минимальная строгая выводимая система типов YadroLang."""
from src.синтаксис import Число,Булево,Строка,Имя,Бинарный,Вызов,Пусть,Присвоить,Вернуть,Если,Пока
Ц64="ц64";БУЛЕВО="булево";СТРОКА="строка";НЕИЗВЕСТНО="неизвестно"
class ОшибкаТипов(Exception):
 def __init__(self,сообщение,код="ЯДРО-Т1000"):self.код=код;super().__init__(f"[{код}] {сообщение}")
class ПроверкаТипов:
 def __init__(self,источники,стоки,санитайзеры):self.источники=set(источники);self.стоки=set(стоки);self.санитайзеры=set(санитайзеры)
 def проверить(self,программа):
  self.функции={ф.имя:ф for ф in программа.функции};self.параметры={ф.имя:[НЕИЗВЕСТНО]*len(ф.параметры) for ф in программа.функции};self.возвраты={ф.имя:НЕИЗВЕСТНО for ф in программа.функции}
  for _ in range(64):
   до=(repr(self.параметры),repr(self.возвраты))
   for ф in программа.функции:self._функция(ф)
   if до==(repr(self.параметры),repr(self.возвраты)):break
  else:raise ОшибкаТипов("Вывод типов не сошёлся","ЯДРО-Т1099")
  for ф in программа.функции:self._функция(ф,True)
  return self
 def _ошибка(self,узел,сообщение,код):raise ОшибкаТипов(f"{сообщение} (строка {узел.строка}).",код)
 def _слить(self,а,б,узел):
  if а==НЕИЗВЕСТНО:return б
  if б==НЕИЗВЕСТНО:return а
  if а!=б:self._ошибка(узел,f"Несовместимые типы: {а} и {б}","ЯДРО-Т1001")
  return а
 def _функция(self,ф,финал=False):
  окружение=dict(zip(ф.параметры,self.параметры[ф.имя]));возвраты=[];self._тело(ф.тело,окружение,возвраты);результат=НЕИЗВЕСТНО
  for тип,узел in возвраты:результат=self._слить(результат,тип,узел)
  if результат==СТРОКА:self._ошибка(ф,"Функция не может возвращать строку","ЯДРО-Т1005")
  if результат==НЕИЗВЕСТНО and финал:результат=Ц64
  self.возвраты[ф.имя]=self._слить(self.возвраты[ф.имя],результат,ф);self.параметры[ф.имя]=[окружение.get(имя,НЕИЗВЕСТНО) for имя in ф.параметры]
 def _тело(self,тело,окружение,возвраты):
  завершено=False
  for у in тело:
   if завершено:self._ошибка(у,"Недостижимое утверждение после безусловного вернуть","ЯДРО-Т1008")
   if isinstance(у,Пусть):
    тип=self._выражение(у.значение,окружение)
    if тип==СТРОКА:self._ошибка(у,"Строки разрешены только как литералы печать","ЯДРО-Т1005")
    окружение[у.имя]=тип
   elif isinstance(у,Присвоить):
    if у.имя not in окружение:self._ошибка(у,f"Неизвестная переменная '{у.имя}'","ЯДРО-Т1006")
    окружение[у.имя]=self._слить(окружение[у.имя],self._выражение(у.значение,окружение),у)
   elif isinstance(у,Вернуть):возвраты.append((self._выражение(у.значение,окружение),у));завершено=True
   elif isinstance(у,Если):
    условие=self._выражение(у.условие,окружение)
    if условие not in (БУЛЕВО,Ц64,НЕИЗВЕСТНО):self._ошибка(у,"условие если должно быть булево или ц64 truthiness","ЯДРО-Т1003")
    левое,правое=dict(окружение),dict(окружение);лв=[];пв=[];лз=self._тело(у.тогда,левое,лв);пз=self._тело(у.иначе,правое,пв) if у.иначе else False
    for имя in set(левое)|set(правое):окружение[имя]=self._слить(левое.get(имя,окружение.get(имя,НЕИЗВЕСТНО)),правое.get(имя,окружение.get(имя,НЕИЗВЕСТНО)),у)
    возвраты.extend(лв);возвраты.extend(пв);завершено=bool(у.иначе) and лз and пз
   elif isinstance(у,Пока):
    условие=self._выражение(у.условие,окружение)
    if условие not in (БУЛЕВО,Ц64,НЕИЗВЕСТНО):self._ошибка(у,"условие пока должно быть булево или ц64 truthiness","ЯДРО-Т1003")
    цикл=dict(окружение);цв=[];self._тело(у.тело,цикл,цв)
    for имя in set(окружение)|set(цикл):окружение[имя]=self._слить(окружение.get(имя,НЕИЗВЕСТНО),цикл.get(имя,НЕИЗВЕСТНО),у)
    возвраты.extend(цв)
   else:self._выражение(у,окружение)
  return завершено
 def _выражение(self,узел,окружение):
  if isinstance(узел,Число):return Ц64
  if isinstance(узел,Булево):return БУЛЕВО
  if isinstance(узел,Строка):return СТРОКА
  if isinstance(узел,Имя):
   if узел.имя not in окружение:self._ошибка(узел,f"Неизвестная переменная '{узел.имя}'","ЯДРО-Т1006")
   return окружение[узел.имя]
  if isinstance(узел,Бинарный):
   слева,справа=self._выражение(узел.слева,окружение),self._выражение(узел.справа,окружение)
   if узел.оп in ("+","-","*","/",">","<"):self._слить(слева,Ц64,узел);self._слить(справа,Ц64,узел);return БУЛЕВО if узел.оп in (">","<") else Ц64
   общий=self._слить(слева,справа,узел)
   if общий==СТРОКА:self._ошибка(узел,"Сравнение строк не поддерживается","ЯДРО-Т1005")
   return БУЛЕВО
  if isinstance(узел,Вызов):
   аргументы=[self._выражение(а,окружение) for а in узел.аргументы]
   if узел.имя=="печать":return Ц64
   if узел.имя in self.источники:return Ц64
   if узел.имя in self.стоки or узел.имя in self.санитайзеры:
    if аргументы and аргументы[0]==СТРОКА:self._ошибка(узел,"Системный API не принимает строку","ЯДРО-Т1004")
    return Ц64
   if узел.имя in self.функции:
    ожидаются=self.параметры[узел.имя]
    for i,тип in enumerate(аргументы):ожидаются[i]=self._слить(ожидаются[i],тип,узел)
    return self.возвраты[узел.имя]
   return Ц64
  self._ошибка(узел,"Невозможно вывести тип выражения","ЯДРО-Т1000")
