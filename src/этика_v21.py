@dataclass
class СводкаВозврата:
    фиксированные: set = field(default_factory=set)
    потоки: dict = field(default_factory=dict)


class ЭтическийАнализатор:
    МАКС_ИТЕРАЦИЙ = 128

    def __init__(self):
        self.функции = {}
        self.сводка_возврата = {}
        self.сводка_утечек = {}
        self.аудит_трейл = []

    def проверить(self, программа: Программа):
        self.функции = {ф.имя: ф for ф in программа.функции}
        self.аудит_трейл = []
        self._запретить_подмену(программа)
        self._вычислить_сводки()
        for функция in программа.функции:
            self._проверить_мандаты(функция)
            self._сканировать_тело(функция.тело, {}, set())
        return self.аудит_трейл

    def _запретить_подмену(self, программа):
        зарезервированы = set(ИСТОЧНИКИ) | set(СТОКИ) | set(САНИТАЙЗЕРЫ) | {"печать"}
        for функция in программа.функции:
            if функция.имя in зарезервированы:
                raise ЭтическаяОшибка(
                    f"Зарезервированный символ политики '{функция.имя}' нельзя переопределять (строка {функция.строка}).",
                    "ЯДРО-Э2101")

    def _вычислить_сводки(self):
        self.сводка_возврата = {имя: СводкаВозврата() for имя in self.функции}
        self.сводка_утечек = {имя: set() for имя in self.функции}
        for _ in range(self.МАКС_ИТЕРАЦИЙ):
            изменилось = False
            for имя, функция in self.функции.items():
                сводка = self._суммировать_возвраты(функция)
                утечки = self._суммировать_утечки(функция)
                if сводка != self.сводка_возврата[имя]:
                    self.сводка_возврата[имя] = сводка
                    изменилось = True
                if утечки != self.сводка_утечек[имя]:
                    self.сводка_утечек[имя] = утечки
                    изменилось = True
            if not изменилось:
                return
        raise ЭтическаяОшибка("Этический анализ не достиг фикспойнта.", "ЯДРО-Э2901")

    def _суммировать_возвраты(self, функция):
        фиксированные = self._метки_возврата(функция.тело, {})
        потоки = {}
        for индекс, параметр in enumerate(функция.параметры):
            for метка in ВСЕ_МЕТКИ:
                выход = self._метки_возврата(функция.тело, {параметр: {метка}})
                разница = выход - фиксированные
                if разница:
                    потоки[(индекс, метка)] = разница
        return СводкаВозврата(фиксированные, потоки)

    def _суммировать_утечки(self, функция):
        утечки = set()
        for индекс, параметр in enumerate(функция.параметры):
            for метка in ВСЕ_МЕТКИ:
                if self._тело_утекает(функция.тело, {параметр: {метка}}, set()):
                    утечки.add((индекс, метка))
        return утечки

    def _метки_возврата(self, тело, вход):
        окружение = self._копия(вход)
        возвраты = set()
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Вернуть):
                возвраты |= self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Если):
                левое, правое = self._копия(окружение), self._копия(окружение)
                возвраты |= self._метки_возврата(утверждение.тогда, левое)
                возвраты |= self._метки_возврата(утверждение.иначе, правое)
                окружение = self._объединить(окружение, левое, правое)
            elif isinstance(утверждение, Пока):
                окружение, возврат_цикла = self._фикспойнт_цикла(утверждение.тело, окружение)
                возвраты |= возврат_цикла
        return возвраты

    def _фикспойнт_цикла(self, тело, вход):
        окружение = self._копия(вход)
        возвраты = set()
        for _ in range(self.МАКС_ИТЕРАЦИЙ):
            окружение_тела = self._копия(окружение)
            возвраты |= self._метки_возврата(тело, окружение_тела)
            объединение = self._объединить(вход, окружение, окружение_тела)
            if объединение == окружение:
                return окружение, возвраты
            окружение = объединение
        raise ЭтическаяОшибка("Анализ цикла не достиг фикспойнта.", "ЯДРО-Э2902")

    def _метки(self, выражение, окружение, аудит=False):
        if выражение is None or isinstance(выражение, (Число, Строка)):
            return set()
        if isinstance(выражение, Имя):
            return set(окружение.get(выражение.имя, set()))
        if isinstance(выражение, Бинарный):
            return self._метки(выражение.слева, окружение, аудит) | self._метки(выражение.справа, окружение, аудит)
        if isinstance(выражение, Вызов):
            метки_аргументов = [self._метки(аргумент, окружение, аудит) for аргумент in выражение.аргументы]
            if выражение.имя in САНИТАЙЗЕРЫ and выражение.имя not in self.функции:
                метки = set().union(*метки_аргументов) if метки_аргументов else set()
                сняты = {метка for метка in метки if выражение.имя in КОМПЛАЕНС.get(метка, set())}
                остаток = метки - сняты
                if аудит:
                    for метка in sorted(сняты):
                        self.аудит_трейл.append(ЗаписьАудита(выражение.имя, метка, [],
                                                             "деклассифицировано", выражение.строка,
                                                             "САНИТАЙЗ", "Деклассификация по метке"))
                return остаток
            if выражение.имя in ИСТОЧНИКИ and выражение.имя not in self.функции:
                return {ИСТОЧНИКИ[выражение.имя]}
            сводка = self.сводка_возврата.get(выражение.имя)
            if сводка:
                результат = set(сводка.фиксированные)
                for индекс, метки in enumerate(метки_аргументов):
                    for метка in метки:
                        результат |= сводка.потоки.get((индекс, метка), set())
                return результат
            return set().union(*метки_аргументов) if метки_аргументов else set()
        return set()

    def _тело_утекает(self, тело, вход, pc_метки):
        окружение = self._копия(вход)
        for утверждение in тело:
            выражение = getattr(утверждение, "значение", утверждение)
            if isinstance(утверждение, (Пусть, Присвоить)):
                if self._выражение_утекает(утверждение.значение, окружение, pc_метки):
                    return True
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Вернуть):
                if self._выражение_утекает(утверждение.значение, окружение, pc_метки):
                    return True
            elif isinstance(утверждение, Если):
                if self._выражение_утекает(утверждение.условие, окружение, pc_метки):
                    return True
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                if self._тело_утекает(утверждение.тогда, self._копия(окружение), дочерние_pc):
                    return True
                if self._тело_утекает(утверждение.иначе, self._копия(окружение), дочерние_pc):
                    return True
            elif isinstance(утверждение, Пока):
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                if self._тело_утекает(утверждение.тело, self._копия(окружение), дочерние_pc):
                    return True
            elif self._выражение_утекает(выражение, окружение, pc_метки):
                return True
        return False

    def _выражение_утекает(self, выражение, окружение, pc_метки):
        if выражение is None:
            return False
        if isinstance(выражение, Бинарный):
            return self._выражение_утекает(выражение.слева, окружение, pc_метки) or self._выражение_утекает(выражение.справа, окружение, pc_метки)
        if isinstance(выражение, Вызов):
            if выражение.имя in СТОКИ:
                return bool(pc_метки) or any(self._метки(аргумент, окружение) for аргумент in выражение.аргументы)
            утечки = self.сводка_утечек.get(выражение.имя, set())
            for индекс, аргумент in enumerate(выражение.аргументы):
                for метка in self._метки(аргумент, окружение):
                    if (индекс, метка) in утечки:
                        return True
            return any(self._выражение_утекает(аргумент, окружение, pc_метки) for аргумент in выражение.аргументы)
        return False

    def _сканировать_тело(self, тело, вход, pc_метки):
        окружение = self._копия(вход)
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                self._сканировать_выражение(утверждение.значение, окружение, pc_метки)
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение, аудит=True)
            elif isinstance(утверждение, Вернуть):
                self._сканировать_выражение(утверждение.значение, окружение, pc_метки)
            elif isinstance(утверждение, Если):
                self._сканировать_выражение(утверждение.условие, окружение, pc_метки)
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                левое, правое = self._копия(окружение), self._копия(окружение)
                self._сканировать_тело(утверждение.тогда, левое, дочерние_pc)
                self._сканировать_тело(утверждение.иначе, правое, дочерние_pc)
                окружение = self._объединить(окружение, левое, правое)
            elif isinstance(утверждение, Пока):
                self._сканировать_выражение(утверждение.условие, окружение, pc_метки)
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                self._сканировать_тело(утверждение.тело, self._копия(окружение), дочерние_pc)
            else:
                self._сканировать_выражение(утверждение, окружение, pc_метки)

    def _сканировать_выражение(self, выражение, окружение, pc_метки):
        if выражение is None:
            return
        if isinstance(выражение, Бинарный):
            self._сканировать_выражение(выражение.слева, окружение, pc_метки)
            self._сканировать_выражение(выражение.справа, окружение, pc_метки)
            return
        if not isinstance(выражение, Вызов):
            return
        if выражение.имя in СТОКИ:
            if pc_метки:
                метки = ", ".join(sorted(pc_метки))
                self.аудит_трейл.append(ЗаписьАудита("неявное-условие", метки, [],
                                                     выражение.имя, выражение.строка,
                                                     "НЕЯВНЫЙ_ПОТОК"))
                raise ЭтическаяОшибка(
                    f"Неявный информационный поток (строка {выражение.строка}): сток '{выражение.имя}' управляется чувствительными данными ({метки}).",
                    "ЯДРО-Э2302")
            утекли = set().union(*(self._метки(аргумент, окружение) for аргумент in выражение.аргументы)) if выражение.аргументы else set()
            if утекли:
                метки = ", ".join(sorted(утекли))
                self.аудит_трейл.append(ЗаписьАудита("прямой", метки, [], выражение.имя,
                                                     выражение.строка, "БЛОК"))
                raise ЭтическаяОшибка(
                    f"Утечка данных (строка {выражение.строка}): данные {метки} достигают стока '{выражение.имя}' без разрешённого санитайзера.",
                    "ЯДРО-Э2301")
        утечки = self.сводка_утечек.get(выражение.имя, set())
        for индекс, аргумент in enumerate(выражение.аргументы):
            for метка in self._метки(аргумент, окружение):
                if (индекс, метка) in утечки:
                    raise ЭтическаяОшибка(
                        f"Утечка данных (строка {выражение.строка}): данные {метка} утекают через параметр {индекс + 1} функции '{выражение.имя}'.",
                        "ЯДРО-Э2303")
        for аргумент in выражение.аргументы:
            self._сканировать_выражение(аргумент, окружение, pc_метки)

    def _проверить_мандаты(self, функция: Функция):
        for вызов in self._все_вызовы(функция.тело):
            нужен = СТОКИ.get(вызов.имя)
            if нужен and нужен not in функция.мандаты:
                raise ЭтическаяОшибка(
                    f"Функция '{функция.имя}' (строка {вызов.строка}) вызывает '{вызов.имя}', требующий мандата [{нужен}].",
                    "ЯДРО-Э2201")
            цель = self.функции.get(вызов.имя)
            if цель:
                for мандат in цель.мандаты:
                    if мандат not in функция.мандаты:
                        raise ЭтическаяОшибка(
                            f"Функция '{функция.имя}' (строка {вызов.строка}) вызывает '{цель.имя}', требующую [{мандат}], но не объявляет её.",
                            "ЯДРО-Э2202")

    def _все_вызовы(self, тело):
        вызовы = []
        def выражение(узел):
            if isinstance(узел, Вызов):
                вызовы.append(узел)
                for аргумент in узел.аргументы:
                    выражение(аргумент)
            elif isinstance(узел, Бинарный):
                выражение(узел.слева); выражение(узел.справа)
        def утверждение(узел):
            if isinstance(узел, (Пусть, Присвоить, Вернуть)):
                выражение(узел.значение)
            elif isinstance(узел, Если):
                выражение(узел.условие)
                for элемент in узел.тогда + узел.иначе:
                    утверждение(элемент)
            elif isinstance(узел, Пока):
                выражение(узел.условие)
                for элемент in узел.тело:
                    утверждение(элемент)
            else:
                выражение(узел)
