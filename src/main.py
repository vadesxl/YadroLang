import sys

def скомпилировать(исходный_код):
    print(f"--- КОМПИЛЯТОР ЯДРО v0.1 ---")
    print(f"Читаю код: {исходный_код}")
    
    # Простейший парсер: ищем команду "вернуть"
    строки = исходный_код.split('\n')
    for строка in строки:
        слова = строка.strip().split()
        if not слова: continue
        
        if слова[0] == "вернуть":
            число = слова[1]
            print(f"ГЕНЕРАЦИЯ: Создаю инструкцию возврата числа {число}")
            print(f"УСПЕХ: Бинарный код создан (эмуляция).")
            return
            
    print("ОШИБКА: Не найдена команда 'вернуть'")

if __name__ == "__main__":
    # Тестовый запуск
    код = "вернуть 777"
    скомпилировать(код)
