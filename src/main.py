class ОшибкаТочкиВхода(Exception):pass
class ОшибкаСемантики(Exception):pass
def _проверить_точку_входа(ast):
 точки=[ф for ф in ast.функции if ф.имя=="старт"]
 if not точки:raise ОшибкаТочкиВхода("Нет точки входа 'старт'.")
 if len(точки)>1:raise ОшибкаТочкиВхода("Точка входа 'старт' должна быть одна.")
 if точки[0].параметры:raise ОшибкаТочкиВхода("'старт' не принимает параметры.")
def _проверить_уникальность_функций(ast):
 видели=set()
 for ф in ast.функции:
  if ф.имя in видели:raise ОшибкаСемантики(f"Функция '{ф.имя}' объявлена повторно (строка {ф.строка}).")
  видели.add(ф.имя)
АРНОСТЬ_СИСТЕМНЫХ_API={**{n:0 for n in ИСТОЧНИКИ},**{n:1 for n in САНИТАЙЗЕРЫ},**{n:1 for n in СТОКИ},"печать":1};СИСТЕМНЫЕ_API=set(АРНОСТЬ_СИСТЕМНЫХ_API)
def _обойти(узел,тип,out):
 if isinstance(узел,тип):out.append(узел)
 значения=getattr(узел,"__dict__",None)
 if значения:
  for значение in значения.values():
   if isinstance(значение,list):
    for элемент in значение:_обойти(элемент,тип,out)
   elif hasattr(значение,"__dict__"):_обойти(значение,тип,out)
def _проверить_вызовы(ast):
 арность={ф.имя:len(ф.параметры) for ф in ast.функции}
 for ф in ast.функции:
  вызовы=[]
  for утверждение in ф.тело:_обойти(утверждение,Вызов,вызовы)
  for вызов in вызовы:
   ожидается=арность.get(вызов.имя,АРНОСТЬ_СИСТЕМНЫХ_API.get(вызов.имя))
   if ожидается is None:raise ОшибкаСемантики(f"Неизвестная функция '{вызов.имя}' (строка {вызов.строка}).")
   if len(вызов.аргументы)!=ожидается:raise ОшибкаСемантики(f"Функция '{вызов.имя}' ожидает {ожидается} арг., получено {len(вызов.аргументы)} (строка {вызов.строка}).")
I64_МИН=-(2**63);I64_МАКС=2**63-1
def _константа(узел):
 if isinstance(узел,Число):return узел.значение
 if not isinstance(узел,Бинарный):return None
 л,п=_константа(узел.слева),_константа(узел.справа)
 if л is None or п is None:return None
 if узел.оп=="+":return л+п
 if узел.оп=="-":return л-п
 if узел.оп=="*":return л*п
 if узел.оп=="/" and п:return abs(л)//abs(п)*(-1 if (л<0)!=(п<0) else 1)
 return None
def _проверить_выражения(ast):
 for ф in ast.функции:
  числа,бинарные=[],[]
  for утверждение in ф.тело:_обойти(утверждение,Число,числа);_обойти(утверждение,Бинарный,бинарные)
  for число in числа:
   if not I64_МИН<=число.значение<=I64_МАКС:raise ОшибкаСемантики(f"Литерал вне i64 (строка {число.строка}).")
  for бинарный in бинарные:
   if бинарный.оп=="/":
    делитель,делимое=_константа(бинарный.справа),_константа(бинарный.слева)
    if делитель==0:raise ОшибкаСемантики(f"Деление на ноль (строка {бинарный.строка}).")
    if делимое==I64_МИН and делитель==-1:raise ОшибкаСемантики(f"Переполнение signed i64 (строка {бинарный.строка}).")
def компилировать(исходник:str,выводить_ir=False)->str:
 ast=Парсер(Лексер(исходник).токены()).разобрать();_проверить_уникальность_функций(ast);_проверить_точку_входа(ast);_проверить_вызовы(ast);_проверить_выражения(ast);ПроверкаТипов(ast,СИСТЕМНЫЕ_API).проверить();ЭтическийАнализатор().проверить(ast);ir=Кодоген().сгенерировать(ast)
 if выводить_ir:print(ir)
 return ir
def собрать_нативно(ir_код:str,выход="ядро.o"):
 for инициализатор in (getattr(llvm,"initialize",None),getattr(llvm,"initialize_native_target",None),getattr(llvm,"initialize_native_asmprinter",None)):
  if инициализатор:
   try:инициализатор()
   except Exception:pass
 модуль=llvm.parse_assembly(ir_код);модуль.verify();цель=llvm.Target.from_default_triple().create_target_machine()
 with open(выход,"wb") as файл:файл.write(цель.emit_object(модуль))
 print(f"[ЯДРО] Объектник: {выход}")
