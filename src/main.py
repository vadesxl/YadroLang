import sys

# Компилятор ЯДРО (v0.7.1 - Стабильные Циклы)
память = {}

def выполнить_строку(строка):
    строка = строка.strip()
    if not строка: return
    
    слова = строка.split()
    команда = слова[0]
    
    # 1. УСТАНОВИТЬ
    if команда == "установить":
        имя = слова[1]
        значение = слова[2]
        if значение.isdigit():
            память[имя] = int(значение)
        else:
            память[имя] = значение.replace('"', '')
        print(f"[СИСТЕМА] {имя} = {память[имя]}")
        
    # 2. СКАЗАТЬ (ИСПРАВЛЕНО - БЕЗОПАСНАЯ ВЕРСИЯ)
    elif команда == "сказать":
        содержимое = строка.split(maxsplit=1)[1]
        if содержимое.startswith('"'):
            чистый_текст = содержимое.replace('"', '')
            print(f"[ВЫВОД] {чистый_текст}")
        elif содержимое in память:
            print(f"[ВЫВОД] {память[содержимое]}")
            
    # 3. МАТЕМАТИКА
    elif команда == "сложить":
        имя = слова[1]
        память[имя] += int(слова[2])
        print(f"[МАТЕМАТИКА] {имя} стало {память[имя]}")
        
    elif команда == "вычесть":
        имя = слова[1]
        память[имя] -= int(слова[2])
        print(f"[МАТЕМАТИКА] {имя} стало {память[имя]}")

    # 4. ЛОГИКА (ЕСЛИ)
    elif команда == "если":
        переменная = слова[1]
        знак = слова[2]
        значение = int(слова[3])
        то_выполнить = " ".join(слова[4:])
        
        текущее = память.get(переменная, 0)
        if (знак == ">" and текущее > значение) or \
           (знак == "<" and текущее < значение) or \
           (знак == "==" and текущее == значение):
            print(f"[ЛОГИКА] Истина -> {то_выполнить}")
            выполнить_строку(то_выполнить)

    # 5. ЦИКЛЫ (ПОКА)
    elif команда == "пока":
        переменная = слова[1]
        знак = слова[2]
        значение = int(слова[3])
        то_выполнить = " ".join(слова[4:])
        
        print(f"--- НАЧАЛО ЦИКЛА ---")
        счетчик_аварии = 0
        
        while True:
            текущее = память.get(переменная, 0)
            условие = False
            if знак == ">": условие = (текущее > значение)
            if знак == "<": условие = (текущее < значение)
            if знак == "==": условие = (текущее == значение)
            
            if not условие:
                break
                
            выполнить_строку(то_выполнить)
            
            счетчик_аварии += 1
            if счетчик_аварии > 50:
                print("⚠️ ПЕРЕГРЕВ ЦИКЛА")
                break
                
        print(f"--- КОНЕЦ ЦИКЛА ---")

    elif команда == "вернуть":
        print(f"--- КОНЕЦ ---")

def скомпилировать(исходный_код):
    print(f"--- ЯДРО v0.7.1 ---")
    строки = исходный_код.split('\n')
    for строка in строки:
        выполнить_строку(строка)

if __name__ == "__main__":
    if len(sys.argv) > 1:
        try:
            with open(sys.argv[1], 'r', encoding='utf-8') as f:
                скомпилировать(f.read())
        except FileNotFoundError:
            print("❌ Файл не найден")
