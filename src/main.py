"""Точка входа компилятора YadroLang и семантическая проверка."""
import sys
from llvmlite import binding as llvm
from src.лексер import Лексер, ОшибкаЛексера
from src.синтаксис import Парсер, ОшибкаПарсера, Вызов, Число, Бинарный
from src.этика import ЭтическийАнализатор, ЭтическаяОшибка, СТОКИ, ИСТОЧНИКИ, САНИТАЙЗЕРЫ
from src.кодоген import Кодоген, ОшибкаКодогена


class ОшибкаТочкиВхода(Exception):
    """Программа не имеет корректной точки входа `старт`."""


class ОшибкаСемантики(Exception):
    """Программа синтаксически корректна, но нарушает семантику языка."""


def _проверить_точку_входа(ast):
    старты = [ф for ф in ast.функции if ф.имя == "старт"]
    if not старты:
        raise ОшибкаТочкиВхода("Нет точки входа: объявите функцию 'старт'.")
    if len(старты) > 1:
        raise ОшибкаТочкиВхода("Точка входа 'старт' должна быть объявлена ровно один раз.")
    if старты[0].параметры:
        raise ОшибкаТочкиВхода("Точка входа 'старт' не должна принимать параметры.")


def _проверить_уникальность_функций(ast):
    известные = set()
    for функция in ast.функции:
        if функция.имя in известные:
            raise ОшибкаСемантики(
                f"Функция '{функция.имя}' объявлена повторно "
                f"(строка {функция.строка}).")
        известные.add(функция.имя)


АРНОСТЬ_СИСТЕМНЫХ_API = {
    **{имя: 0 for имя in ИСТОЧНИКИ},
    **{имя: 1 for имя in САНИТАЙЗЕРЫ},
    **{имя: 1 for имя in СТОКИ},
    "печать": 1,
}
СИСТЕМНЫЕ_API = set(АРНОСТЬ_СИСТЕМНЫХ_API)


def _собрать_вызовы(узел, результат):
    if isinstance(узел, Вызов):
        результат.append(узел)
    значения = getattr(узел, "__dict__", None)
    if not значения:
        return
    for значение in значения.values():
        if isinstance(значение, list):
            for элемент in значение:
                _собрать_вызовы(элемент, результат)
        elif hasattr(значение, "__dict__"):
            _собрать_вызовы(значение, результат)


def _проверить_вызовы(ast):
    арность = {ф.имя: len(ф.параметры) for ф in ast.функции}
    for функция in ast.функции:
        вызовы = []
        for утверждение in функция.тело:
            _собрать_вызовы(утверждение, вызовы)
        for вызов in вызовы:
            ожидается = арность.get(вызов.имя, АРНОСТЬ_СИСТЕМНЫХ_API.get(вызов.имя))
            if ожидается is None:
                raise ОшибкаСемантики(
                    f"Неизвестная функция '{вызов.имя}' (строка {вызов.строка}).")
            if len(вызов.аргументы) != ожидается:
                raise ОшибкаСемантики(
                    f"Функция '{вызов.имя}' ожидает {ожидается} арг., "
                    f"получено {len(вызов.аргументы)} (строка {вызов.строка}).")


I64_МИН = -(2 ** 63)
I64_МАКС = 2 ** 63 - 1


def _собрать_узлы(узел, тип_узла, результат):
    if isinstance(узел, тип_узла):
        результат.append(узел)
    значения = getattr(узел, "__dict__", None)
    if not значения:
        return
    for значение in значения.values():
        if isinstance(значение, list):
            for элемент in значение:
                _собрать_узлы(элемент, тип_узла, результат)
        elif hasattr(значение, "__dict__"):
            _собрать_узлы(значение, тип_узла, результат)


def _константное_целое(узел):
    """Вычислить целочисленное выражение без побочных эффектов, если возможно."""
    if isinstance(узел, Число):
        return узел.значение
    if not isinstance(узел, Бинарный):
        return None
    слева = _константное_целое(узел.слева)
    справа = _константное_целое(узел.справа)
    if слева is None or справа is None:
        return None
    if узел.оп == "+":
        return слева + справа
    if узел.оп == "-":
        return слева - справа
    if узел.оп == "*":
        return слева * справа
    if узел.оп == "/" and справа != 0:
        return abs(слева) // abs(справа) * (-1 if (слева < 0) != (справа < 0) else 1)
    return None


def _проверить_выражения(ast):
    for функция in ast.функции:
        числа, бинарные = [], []
        for утверждение in функция.тело:
            _собрать_узлы(утверждение, Число, числа)
            _собрать_узлы(утверждение, Бинарный, бинарные)
        for число in числа:
            if not (I64_МИН <= число.значение <= I64_МАКС):
                raise ОшибкаСемантики(
                    f"Числовой литерал {число.значение} вне диапазона i64 "
                    f"(строка {число.строка}).")
        for бинарный in бинарные:
            if бинарный.оп != "/":
                continue
            делитель = _константное_целое(бинарный.справа)
            делимое = _константное_целое(бинарный.слева)
            if делитель == 0:
                raise ОшибкаСемантики(f"Деление на ноль (строка {бинарный.строка}).")
            if делимое == I64_МИН and делитель == -1:
                raise ОшибкаСемантики(
                    f"Переполнение знакового деления i64 (строка {бинарный.строка}).")


def компилировать(исходник: str, выводить_ir=False) -> str:
    токены = Лексер(исходник).токены()
    ast = Парсер(токены).разобрать()
    _проверить_уникальность_функций(ast)
    _проверить_точку_входа(ast)
    _проверить_вызовы(ast)
    _проверить_выражения(ast)
    ЭтическийАнализатор().проверить(ast)
    ir_код = Кодоген().сгенерировать(ast)
    if выводить_ir:
        print(ir_код)
    return ir_код


def собрать_нативно(ir_код: str, выход="ядро.o"):
    for инициализатор in (
        getattr(llvm, "initialize", None),
        getattr(llvm, "initialize_native_target", None),
        getattr(llvm, "initialize_native_asmprinter", None),
    ):
        if инициализатор is not None:
            try:
                инициализатор()
            except Exception:
                pass
    модуль = llvm.parse_assembly(ir_код)
    модуль.verify()
    try:
        pmb = llvm.create_pass_manager_builder()
        pmb.opt_level = 2
        pm = llvm.create_module_pass_manager()
        pmb.populate(pm)
        pm.run(модуль)
    except AttributeError:
        try:
            машина = llvm.Target.from_default_triple().create_target_machine()
            pb = llvm.create_pass_builder(машина, llvm.PipelineTuningOptions(speed_level=2))
            pb.getModulePassManager().run(модуль, pb)
        except Exception:
            pass
    цель = llvm.Target.from_default_triple().create_target_machine()
    with open(выход, "wb") as объектник:
        объектник.write(цель.emit_object(модуль))
    print(f"[ЯДРО] Нативный объектник: {выход}")


def главная():
    if len(sys.argv) < 2:
        print("Использование: python -m src.main файл.яд [--ir]")
        sys.exit(1)
    try:
        with open(sys.argv[1], encoding="utf-8") as файл:
            исходник = файл.read()
        ir_код = компилировать(исходник, выводить_ir="--ir" in sys.argv)
        if "--ir" not in sys.argv:
            собрать_нативно(ir_код)
    except (OSError, ОшибкаТочкиВхода, ОшибкаСемантики, ЭтическаяОшибка,
            ОшибкаПарсера, ОшибкаЛексера, ОшибкаКодогена, RuntimeError) as ошибка:
        print(f"[ЯДРО] Ошибка компиляции: {ошибка}")
        sys.exit(1)
    print("[ЯДРО] Компиляция завершена. Код - это закон.")


if __name__ == "__main__":
    главная()
