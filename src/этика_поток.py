# -*- coding: utf-8 -*-
"""Корректные слияния control-flow для Этического анализатора v2.1."""
from src.этика_v21 import ЭтическийАнализатор
from src.синтаксис import Пусть, Присвоить, Вернуть, Если, Пока


class ЗвуковойЭтическийАнализатор(ЭтическийАнализатор):
    def _поток_тела(self, тело, вход):
        окружение = self._копия(вход)
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Если):
                левое = self._поток_тела(утверждение.тогда, окружение)
                правое = self._поток_тела(утверждение.иначе, окружение)
                окружение = self._объединить(окружение, левое, правое)
            elif isinstance(утверждение, Пока):
                окружение = self._поток_цикла(утверждение.тело, окружение)
        return окружение

    def _поток_цикла(self, тело, вход):
        окружение = self._копия(вход)
        for _ in range(self.МАКС_ИТЕРАЦИЙ):
            окружение_тела = self._поток_тела(тело, окружение)
            объединение = self._объединить(вход, окружение, окружение_тела)
            if объединение == окружение:
                return окружение
            окружение = объединение
        raise RuntimeError("фикспойнт потока цикла не сошёлся")

    def _метки_возврата(self, тело, вход):
        окружение = self._копия(вход)
        возвраты = set()
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Вернуть):
                возвраты |= self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Если):
                возвраты |= self._метки_возврата(утверждение.тогда, окружение)
                возвраты |= self._метки_возврата(утверждение.иначе, окружение)
                окружение = self._объединить(окружение,
                                             self._поток_тела(утверждение.тогда, окружение),
                                             self._поток_тела(утверждение.иначе, окружение))
            elif isinstance(утверждение, Пока):
                окружение_цикла = self._поток_цикла(утверждение.тело, окружение)
                возвраты |= self._метки_возврата(утверждение.тело, окружение_цикла)
                окружение = окружение_цикла
        return возвраты

    def _тело_утекает(self, тело, вход, pc_метки):
        окружение = self._копия(вход)
        for утверждение in тело:
            выражение = getattr(утверждение, "значение", утверждение)
            if isinstance(утверждение, (Пусть, Присвоить)):
                if self._выражение_утекает(утверждение.значение, окружение, pc_метки):
                    return True
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение)
            elif isinstance(утверждение, Вернуть):
                if self._выражение_утекает(утверждение.значение, окружение, pc_метки):
                    return True
            elif isinstance(утверждение, Если):
                if self._выражение_утекает(утверждение.условие, окружение, pc_метки):
                    return True
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                if self._тело_утекает(утверждение.тогда, окружение, дочерние_pc):
                    return True
                if self._тело_утекает(утверждение.иначе, окружение, дочерние_pc):
                    return True
                окружение = self._объединить(окружение,
                                             self._поток_тела(утверждение.тогда, окружение),
                                             self._поток_тела(утверждение.иначе, окружение))
            elif isinstance(утверждение, Пока):
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                окружение_цикла = self._поток_цикла(утверждение.тело, окружение)
                if self._тело_утекает(утверждение.тело, окружение_цикла, дочерние_pc):
                    return True
                окружение = окружение_цикла
            elif self._выражение_утекает(выражение, окружение, pc_метки):
                return True
        return False

    def _сканировать_тело(self, тело, вход, pc_метки):
        окружение = self._копия(вход)
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                self._сканировать_выражение(утверждение.значение, окружение, pc_метки)
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение, аудит=True)
            elif isinstance(утверждение, Вернуть):
                self._сканировать_выражение(утверждение.значение, окружение, pc_метки)
            elif isinstance(утверждение, Если):
                self._сканировать_выражение(утверждение.условие, окружение, pc_метки)
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                self._сканировать_тело(утверждение.тогда, окружение, дочерние_pc)
                self._сканировать_тело(утверждение.иначе, окружение, дочерние_pc)
                окружение = self._объединить(окружение,
                                             self._поток_тела(утверждение.тогда, окружение),
                                             self._поток_тела(утверждение.иначе, окружение))
            elif isinstance(утверждение, Пока):
                self._сканировать_выражение(утверждение.условие, окружение, pc_метки)
                дочерние_pc = set(pc_метки) | self._метки(утверждение.условие, окружение)
                окружение_цикла = self._поток_цикла(утверждение.тело, окружение)
                self._сканировать_тело(утверждение.тело, окружение_цикла, дочерние_pc)
                окружение = окружение_цикла
            else:
                self._сканировать_выражение(утверждение, окружение, pc_метки)
        return окружение
