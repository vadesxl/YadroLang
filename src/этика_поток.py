# -*- coding: utf-8 -*-
"""Корректные слияния control-flow для Этического анализатора v2.1.

PATCH 1–3 (issue #47) — управляющий контекст (pc_метки):
  PATCH 1: печать — выводной сток. Проверяется ПОТОК МЕТОК, а не мандат,
           поэтому печать(константа) компилируется без [ВыводПрограммы],
           а печать(секрет) отсекается как утечка.
  PATCH 2: присвоение под чувствительным условием переносит pc_метки в переменную.
  PATCH 3: возврат под чувствительным условием переносит pc_метки в метки возврата.

Анализатор сохраняет корректные слияния ветвей и фикспойнт цикла из этой ветки
(в отличие от копии этика_v21_patched, которая их теряет — см. AUDIT_REPORT §2.3).
"""
from src.этика_v21 import (ЭтическийАнализатор, ЗаписьАудита, ЭтическаяОшибка,
                           СТОКИ)
from src.синтаксис import (Пусть, Присвоить, Вернуть, Если, Пока,
                           Вызов, Бинарный)

# Выводные стоки: участвуют в проверке потока меток, но НЕ требуют мандата (PATCH 1).
ВЫВОД_ПРОГРАММЫ = frozenset({"печать"})


class ЗвуковойЭтическийАнализатор(ЭтическийАнализатор):
    def _это_сток(self, имя):
        # печать — сток для потока меток, но мандата не требует (PATCH 1).
        return имя in СТОКИ or имя in ВЫВОД_ПРОГРАММЫ

    def _поток_тела(self, тело, вход, pc_метки=None):
        if pc_метки is None:
            pc_метки = set()
        pc_метки = set(pc_метки)
        окружение = self._копия(вход)
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                # PATCH 2: управляющий контекст ветви переносит метки в переменную.
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение) | pc_метки
            elif isinstance(утверждение, Если):
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                левое = self._поток_тела(утверждение.тогда, окружение, дочерние_pc)
                правое = self._поток_тела(утверждение.иначе, окружение, дочерние_pc)
                окружение = self._объединить(окружение, левое, правое)
            elif isinstance(утверждение, Пока):
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                окружение = self._поток_цикла(утверждение.тело, окружение, дочерние_pc)
        return окружение

    def _поток_цикла(self, тело, вход, pc_метки=None):
        if pc_метки is None:
            pc_метки = set()
        pc_метки = set(pc_метки)
        окружение = self._копия(вход)
        for _ in range(self.МАКС_ИТЕРАЦИЙ):
            окружение_тела = self._поток_тела(тело, окружение, pc_метки)
            объединение = self._объединить(вход, окружение, окружение_тела)
            if объединение == окружение:
                return окружение
            окружение = объединение
        raise RuntimeError("фикспойнт потока цикла не сошёлся")

    def _метки_возврата(self, тело, вход, pc_метки=None):
        if pc_метки is None:
            pc_метки = set()
        pc_метки = set(pc_метки)
        окружение = self._копия(вход)
        возвраты = set()
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                # PATCH 2: контекст условия переносит метки в присвоенную переменную.
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение) | pc_метки
            elif isinstance(утверждение, Вернуть):
                # PATCH 3: контекст условия переносит метки в возвращаемое значение.
                возвраты |= (self._метки(утверждение.значение, окружение) | pc_метки)
            elif isinstance(утверждение, Если):
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                возвраты |= self._метки_возврата(утверждение.тогда, окружение, дочерние_pc)
                возвраты |= self._метки_возврата(утверждение.иначе, окружение, дочерние_pc)
                окружение = self._объединить(окружение,
                                             self._поток_тела(утверждение.тогда, окружение, дочерние_pc),
                                             self._поток_тела(утверждение.иначе, окружение, дочерние_pc))
            elif isinstance(утверждение, Пока):
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                окружение_цикла = self._поток_цикла(утверждение.тело, окружение, дочерние_pc)
                возвраты |= self._метки_возврата(утверждение.тело, окружение_цикла, дочерние_pc)
                окружение = окружение_цикла
        return возвраты

    def _тело_утекает(self, тело, вход, pc_метки):
        pc_метки = set(pc_метки)
        окружение = self._копия(вход)
        for утверждение in тело:
            выражение = getattr(утверждение, "значение", утверждение)
            if isinstance(утверждение, (Пусть, Присвоить)):
                if self._выражение_утекает(утверждение.значение, окружение, pc_метки):
                    return True
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение) | pc_метки
            elif isinstance(утверждение, Вернуть):
                if self._выражение_утекает(утверждение.значение, окружение, pc_метки):
                    return True
            elif isinstance(утверждение, Если):
                if self._выражение_утекает(утверждение.условие, окружение, pc_метки):
                    return True
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                if self._тело_утекает(утверждение.тогда, self._копия(окружение), дочерние_pc):
                    return True
                if self._тело_утекает(утверждение.иначе, self._копия(окружение), дочерние_pc):
                    return True
            elif isinstance(утверждение, Пока):
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                окружение_цикла = self._поток_цикла(утверждение.тело, окружение, дочерние_pc)
                if self._тело_утекает(утверждение.тело, окружение_цикла, дочерние_pc):
                    return True
                окружение = окружение_цикла
            elif self._выражение_утекает(выражение, окружение, pc_метки):
                return True
        return False

    def _сканировать_тело(self, тело, вход, pc_метки):
        pc_метки = set(pc_метки)
        окружение = self._копия(вход)
        for утверждение in тело:
            if isinstance(утверждение, (Пусть, Присвоить)):
                self._сканировать_выражение(утверждение.значение, окружение, pc_метки)
                окружение[утверждение.имя] = self._метки(утверждение.значение, окружение, аудит=True) | pc_метки
            elif isinstance(утверждение, Вернуть):
                self._сканировать_выражение(утверждение.значение, окружение, pc_метки)
            elif isinstance(утверждение, Если):
                self._сканировать_выражение(утверждение.условие, окружение, pc_метки)
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                self._сканировать_тело(утверждение.тогда, окружение, дочерние_pc)
                self._сканировать_тело(утверждение.иначе, окружение, дочерние_pc)
                окружение = self._объединить(окружение,
                                             self._поток_тела(утверждение.тогда, окружение, дочерние_pc),
                                             self._поток_тела(утверждение.иначе, окружение, дочерние_pc))
            elif isinstance(утверждение, Пока):
                self._сканировать_выражение(утверждение.условие, окружение, pc_метки)
                дочерние_pc = pc_метки | self._метки(утверждение.условие, окружение)
                окружение_цикла = self._поток_цикла(утверждение.тело, окружение, дочерние_pc)
                self._сканировать_тело(утверждение.тело, окружение_цикла, дочерние_pc)
                окружение = окружение_цикла
            else:
                self._сканировать_выражение(утверждение, окружение, pc_метки)
        return окружение

    def _выражение_утекает(self, выражение, окружение, pc_метки):
        if выражение is None:
            return False
        if isinstance(выражение, Бинарный):
            return (self._выражение_утекает(выражение.слева, окружение, pc_метки)
                    or self._выражение_утекает(выражение.справа, окружение, pc_метки))
        if isinstance(выражение, Вызов):
            if self._это_сток(выражение.имя):
                return bool(pc_метки) or any(self._метки(аргумент, окружение) for аргумент in выражение.аргументы)
            утечки = self.сводка_утечек.get(выражение.имя, set())
            for индекс, аргумент in enumerate(выражение.аргументы):
                for метка in self._метки(аргумент, окружение):
                    if (индекс, метка) in утечки:
                        return True
            return any(self._выражение_утекает(аргумент, окружение, pc_метки) for аргумент in выражение.аргументы)
        return False

    def _сканировать_выражение(self, выражение, окружение, pc_метки):
        if выражение is None:
            return
        if isinstance(выражение, Бинарный):
            self._сканировать_выражение(выражение.слева, окружение, pc_метки)
            self._сканировать_выражение(выражение.справа, окружение, pc_метки)
            return
        if not isinstance(выражение, Вызов):
            return
        if self._это_сток(выражение.имя):
            if pc_метки:
                метки = ", ".join(sorted(pc_метки))
                self.аудит_трейл.append(ЗаписьАудита("неявное-условие", метки, [],
                                                     выражение.имя, выражение.строка,
                                                     "НЕЯВНЫЙ_ПОТОК"))
                raise ЭтическаяОшибка(
                    f"Неявный информационный поток (строка {выражение.строка}): сток '{выражение.имя}' управляется чувствительными данными ({метки}).",
                    "ЯДРО-Э2302")
            утекли = set().union(*(self._метки(аргумент, окружение) for аргумент in выражение.аргументы)) if выражение.аргументы else set()
            if утекли:
                метки = ", ".join(sorted(утекли))
                self.аудит_трейл.append(ЗаписьАудита("прямой", метки, [], выражение.имя,
                                                     выражение.строка, "БЛОК"))
                raise ЭтическаяОшибка(
                    f"Утечка данных (строка {выражение.строка}): данные {метки} достигают стока '{выражение.имя}' без разрешённого санитайзера.",
                    "ЯДРО-Э2301")
        утечки = self.сводка_утечек.get(выражение.имя, set())
        for индекс, аргумент in enumerate(выражение.аргументы):
            for метка in self._метки(аргумент, окружение):
                if (индекс, метка) in утечки:
                    raise ЭтическаяОшибка(
                        f"Утечка данных (строка {выражение.строка}): данные {метка} утекают через параметр {индекс + 1} функции '{выражение.имя}'.",
                        "ЯДРО-Э2303")
        for аргумент in выражение.аргументы:
            self._сканировать_выражение(аргумент, окружение, pc_метки)
