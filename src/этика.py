# -*- coding: utf-8 -*-
"""Этический анализатор YadroLang - закон на уровне компиляции.

Двухуровневая модель безопасности ИИ:

  1. МАНДАТЫ (capabilities). Опасный системный API (сеть, диск) вызывается
     только из функции, в сигнатуре которой явно объявлен соответствующий
     мандат 'требует [...]'. Мандат проверяется транзитивно: если функция A
     вызывает B, требующую [ДоступСети], то A тоже обязана объявить его.
     Итог: всё взаимодействие с миром видно в сигнатурах. Спрятать нельзя.

  2. TAINT-АНАЛИЗ (потоковый, по переменным). Данные из источников личной
     информации помечаются как 'заражённые'. Заражение распространяется через
     присваивания, бинарные операции и вызовы функций. Если заражённое
     значение достигает стока (сеть/диск) без прохождения через санитайзер -
     компиляция падает. Очистить можно только явно: обернуть в санитайзер
     (анонимизация / проверка согласия).

Закон до кода. Спрятать вредоносное поведение невозможно.
"""
from src.синтаксис import (Программа, Функция, Вернуть, Пусть, Присвоить,
                           Если, Пока, Число, Строка, Имя, Бинарный, Вызов)


# Сток -> мандат, которого он требует.
СТОКИ = {
    "сеть.отправить": "ДоступСети",
    "сеть.запрос": "ДоступСети",
    "файл.записать": "ЗаписьДиска",
    "файл.удалить": "ЗаписьДиска",
}

# Источники личных/чувствительных данных. Их результат заражён.
ИСТОЧНИКИ = {
    "пользователь.данные",
    "пользователь.имя",
    "личные.прочитать",
    "файл.прочитать",
    "сеть.принять",
}

# Санитайзеры. Их результат гарантированно чист (анонимизация/согласие).
САНИТАЙЗЕРЫ = {
    "анонимизировать",
    "обезличить",
    "проверить_согласие",
    "хэш",
}


class ЭтическаяОшибка(Exception):
    ...


class ЭтическийАнализатор:
    def __init__(self):
        self.функции = {}

    def проверить(self, прог: Программа):
        self.функции = {ф.имя: ф for ф in прог.функции}
        for ф in прог.функции:
            self._мандаты(ф)
            self._taint(ф)

    # --- Уровень 1: мандаты (capabilities) ---
    def _мандаты(self, ф: Функция):
        for утв in ф.тело:
            for вызов in self._все_вызовы_в(утв):
                нужен = СТОКИ.get(вызов.имя)
                if нужен and нужен not in ф.мандаты:
                    raise ЭтическаяОшибка(
                        f"Функция '{ф.имя}' (строка {вызов.строка}) вызывает "
                        f"'{вызов.имя}', требующий мандат [{нужен}], "
                        f"но мандат не объявлен в сигнатуре. "
                        f"Добавьте: функ {ф.имя}(...) требует [{нужен}]")
                # транзитивная проверка пользовательских функций
                цель = self.функции.get(вызов.имя)
                if цель:
                    for м in цель.мандаты:
                        if м not in ф.мандаты:
                            raise ЭтическаяОшибка(
                                f"Функция '{ф.имя}' (строка {вызов.строка}) "
                                f"вызывает '{цель.имя}', требующую [{м}], "
                                f"но сама мандат [{м}] не объявляет.")

    # --- Уровень 2: потоковый taint-анализ ---
    def _taint(self, ф: Функция):
        заражены = set()          # имена заражённых переменных
        for утв in ф.тело:
            self._taint_утв(утв, заражены)

    def _taint_утв(self, у, заражены: set):
        if isinstance(у, Пусть):
            self._проверить_стоки(у.значение, заражены)   # сток в инициализаторе
            if self._заражено(у.значение, заражены):
                заражены.add(у.имя)
            else:
                заражены.discard(у.имя)
        elif isinstance(у, Присвоить):
            self._проверить_стоки(у.значение, заражены)   # сток в правой части
            if self._заражено(у.значение, заражены):
                заражены.add(у.имя)
            else:
                заражены.discard(у.имя)
        elif isinstance(у, Вернуть):
            self._проверить_стоки(у.значение, заражены)
        elif isinstance(у, Если):
            self._проверить_стоки(у.условие, заражены)
            вет = заражены.copy()
            for s in у.тогда:
                self._taint_утв(s, вет)
            вет2 = заражены.copy()
            for s in у.иначе:
                self._taint_утв(s, вет2)
            заражены |= (вет | вет2)   # консервативное слияние ветвей
        elif isinstance(у, Пока):
            self._проверить_стоки(у.условие, заражены)
            # Тело может выполниться 0..N раз. Итерируем анализ тела до
            # НАСТОЯЩЕГО фикспойнта: повторяем, пока множество заражённых
            # растёт. Заражение только ДОБАВЛЯЕТСЯ (санитайзер внутри цикла
            # не гарантирован - итераций может быть 0). На последнем проходе
            # стоки проверяются уже на стабилизированном множестве, поэтому
            # цепочки a=b; b=c; c=источник(); сток(a) ловятся.
            while True:
                до = len(заражены)
                тело_зар = заражены.copy()
                for s in у.тело:
                    self._taint_утв(s, тело_зар)
                заражены |= тело_зар
                if len(заражены) == до:
                    break
        else:
            self._проверить_стоки(у, заражены)

    def _проверить_стоки(self, в, заражены: set):
        """Ищет вызовы стоков и проверяет, что их аргументы не заражены."""
        if в is None:
            return
        if isinstance(в, Вызов):
            if в.имя in СТОКИ:
                for арг in в.аргументы:
                    if self._заражено(арг, заражены):
                        raise ЭтическаяОшибка(
                            f"УТЕЧКА ДАННЫХ (строка {в.строка}): личные данные "
                            f"уходят через сток '{в.имя}' без очистки. "
                            f"Оберните данные в санитайзер "
                            f"({' / '.join(sorted(САНИТАЙЗЕРЫ))}).")
            for арг in в.аргументы:
                self._проверить_стоки(арг, заражены)
        elif isinstance(в, Бинарный):
            self._проверить_стоки(в.слева, заражены)
            self._проверить_стоки(в.справа, заражены)

    def _заражено(self, в, заражены: set) -> bool:
        """Заражено ли выражение хотя бы частично?"""
        if isinstance(в, (Число, Строка)):
            return False
        if isinstance(в, Имя):
            return в.имя in заражены
        if isinstance(в, Бинарный):
            return self._заражено(в.слева, заражены) or self._заражено(в.справа, заражены)
        if isinstance(в, Вызов):
            if в.имя in САНИТАЙЗЕРЫ:
                return False                      # результат санитайзера чист
            if в.имя in ИСТОЧНИКИ:
                return True                       # источник личных данных
            # обычный вызов: заражён, если заражён любой аргумент
            return any(self._заражено(а, заражены) for а in в.аргументы)
        return False

    # --- вспомогательное: собрать все вызовы внутри утверждения ---
    def _все_вызовы_в(self, у):
        out = []

        def обойти_выр(в):
            if isinstance(в, Вызов):
                out.append(в)
                for а in в.аргументы:
                    обойти_выр(а)
            elif isinstance(в, Бинарный):
                обойти_выр(в.слева); обойти_выр(в.справа)

        def обойти_утв(s):
            if isinstance(s, (Пусть, Присвоить, Вернуть)):
                if getattr(s, "значение", None) is not None:
                    обойти_выр(s.значение)
            elif isinstance(s, Если):
                обойти_выр(s.условие)
                for x in s.тогда: обойти_утв(x)
                for x in s.иначе: обойти_утв(x)
            elif isinstance(s, Пока):
                обойти_выр(s.условие)
                for x in s.тело: обойти_утв(x)
            else:
                обойти_выр(s)

        обойти_утв(у)
        return out
