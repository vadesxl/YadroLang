# -*- coding: utf-8 -*-
"""Этический анализатор YadroLang - закон на уровне компиляции.

Двухуровневая модель безопасности ИИ:

  1. МАНДАТЫ (capabilities). Опасный системный API (сеть, диск) вызывается
     только из функции, в сигнатуре которой явно объявлен соответствующий
     мандат 'требует [...]'. Мандат проверяется транзитивно: если функция A
     вызывает B, требующую [ДоступСети], то A тоже обязана объявить его.
     Итог: всё взаимодействие с миром видно в сигнатурах. Спрятать нельзя.

  2. TAINT-АНАЛИЗ (потоковый, по переменным). Данные из источников личной
     информации помечаются как 'заражённые'. Заражение распространяется через
     присваивания, бинарные операции и вызовы функций. Если заражённое
     значение достигает стока (сеть/диск) без прохождения через санитайзер -
     компиляция падает. Очистить можно только явно: обернуть в санитайзер
     (анонимизация / проверка согласия).

Закон до кода. Спрятать вредоносное поведение невозможно.
"""
from src.синтаксис import (Программа, Функция, Вернуть, Пусть, Присвоить,
                           Если, Пока, Число, Строка, Имя, Бинарный, Вызов)


# Сток -> мандат, которого он требует.
СТОКИ = {
    "сеть.отправить": "ДоступСети",
    "сеть.запрос": "ДоступСети",
    "файл.записать": "ЗаписьДиска",
    "файл.удалить": "ЗаписьДиска",
}

# Источники личных/чувствительных данных. Их результат заражён.
ИСТОЧНИКИ = {
    "пользователь.данные",
    "пользователь.имя",
    "личные.прочитать",
    "файл.прочитать",
    "сеть.принять",
}

# Санитайзеры. Их результат гарантированно чист (анонимизация/согласие).
САНИТАЙЗЕРЫ = {
    "анонимизировать",
    "обезличить",
    "проверить_согласие",
    "хэш",
}


class ЭтическаяОшибка(Exception):
    ...


class ЭтическийАнализатор:
    def __init__(self):
        self.функции = {}

    def проверить(self, прог: Программа):
        self.функции = {ф.имя: ф for ф in прог.функции}
        self._вычислить_сводки_возврата()   # какие функции возвращают заражение
        self._вычислить_сводки_параметров()  # какие параметры утекают в сток
        for ф in прог.функции:
            self._мандаты(ф)
            self._taint(ф)

    def _вычислить_сводки_возврата(self):
        """Фикспойнт: для каждой функции - может ли её ВОЗВРАТ нести заражение,
        возникшее внутри неё (из источников или из заражающих вызовов).
        Параметры считаем чистыми: заражение через аргумент ловится на месте
        вызова отдельно. Монотонный рост от False - корректно для рекурсии."""
        self.сводка_возврата = {имя: False for имя in self.функции}
        while True:
            изменилось = False
            for имя, ф in self.функции.items():
                if self.сводка_возврата[имя]:
                    continue
                if self._тело_возвращает_заражение(ф.тело, set()):
                    self.сводка_возврата[имя] = True
                    изменилось = True
            if not изменилось:
                break

    def _тело_возвращает_заражение(self, тело, заражены: set) -> bool:
        возвр = False
        for у in тело:
            if isinstance(у, (Пусть, Присвоить)):
                if self._заражено(у.значение, заражены):
                    заражены.add(у.имя)
                else:
                    заражены.discard(у.имя)
            elif isinstance(у, Вернуть):
                if у.значение is not None and self._заражено(у.значение, заражены):
                    возвр = True
            elif isinstance(у, Если):
                a = заражены.copy(); b = заражены.copy()
                возвр = self._тело_возвращает_заражение(у.тогда, a) or возвр
                возвр = self._тело_возвращает_заражение(у.иначе, b) or возвр
                заражены |= a | b
            elif isinstance(у, Пока):
                while True:
                    до = len(заражены)
                    возвр = self._тело_возвращает_заражение(у.тело, заражены) or возвр
                    if len(заражены) == до:
                        break
        return возвр

    # --- Уровень 1: мандаты (capabilities) ---
    def _мандаты(self, ф: Функция):
        for утв in ф.тело:
            for вызов in self._все_вызовы_в(утв):
                нужен = СТОКИ.get(вызов.имя)
                if нужен and нужен not in ф.мандаты:
                    raise ЭтическаяОшибка(
                        f"Функция '{ф.имя}' (строка {вызов.строка}) вызывает "
                        f"'{вызов.имя}', требующий мандат [{нужен}], "
                        f"но мандат не объявлен в сигнатуре. "
                        f"Добавьте: функ {ф.имя}(...) требует [{нужен}]")
                # транзитивная проверка пользовательских функций
                цель = self.функции.get(вызов.имя)
                if цель:
                    for м in цель.мандаты:
                        if м not in ф.мандаты:
                            raise ЭтическаяОшибка(
                                f"Функция '{ф.имя}' (строка {вызов.строка}) "
                                f"вызывает '{цель.имя}', требующую [{м}], "
                                f"но сама мандат [{м}] не объявляет.")

    # --- Уровень 2: потоковый taint-анализ ---
    def _taint(self, ф: Функция):
        заражены = set()          # имена заражённых переменных
        for утв in ф.тело:
            self._taint_утв(утв, заражены)

    def _taint_утв(self, у, заражены: set):
        if isinstance(у, Пусть):
            self._проверить_стоки(у.значение, заражены)   # сток в инициализаторе
            if self._заражено(у.значение, заражены):
                заражены.add(у.имя)
            else:
                заражены.discard(у.имя)
        elif isinstance(у, Присвоить):
            self._проверить_стоки(у.значение, заражены)   # сток в правой части
            if self._заражено(у.значение, заражены):
                заражены.add(у.имя)
            else:
                заражены.discard(у.имя)
        elif isinstance(у, Вернуть):
            self._проверить_стоки(у.значение, заражены)
        elif isinstance(у, Если):
            self._проверить_стоки(у.условие, заражены)
            вет = заражены.copy()
            for s in у.тогда:
                self._taint_утв(s, вет)
            вет2 = заражены.copy()
            for s in у.иначе:
                self._taint_утв(s, вет2)
            заражены |= (вет | вет2)   # консервативное слияние ветвей
        elif isinstance(у, Пока):
            self._проверить_стоки(у.условие, заражены)
            # Тело может выполниться 0..N раз. Итерируем анализ тела до
            # НАСТОЯЩЕГО фикспойнта: повторяем, пока множество заражённых
            # растёт. Заражение только ДОБАВЛЯЕТСЯ (санитайзер внутри цикла
            # не гарантирован - итераций может быть 0). На последнем проходе
            # стоки проверяются уже на стабилизированном множестве, поэтому
            # цепочки a=b; b=c; c=источник(); сток(a) ловятся.
            while True:
                до = len(заражены)
                тело_зар = заражены.copy()
                for s in у.тело:
                    self._taint_утв(s, тело_зар)
                заражены |= тело_зар
                if len(заражены) == до:
                    break
        else:
            self._проверить_стоки(у, заражены)

    def _вычислить_сводки_параметров(self):
        """Фикспойнт: для каждой функции - множество её параметров, которые,
        будучи заражёнными, утекают в сток (напрямую или транзитивно через
        вызовы других функций). Закрывает межпроцедурную утечку через аргумент."""
        self.сводка_параметров = {имя: set() for имя in self.функции}
        менялось = True
        while менялось:
            менялось = False
            for имя, ф in self.функции.items():
                for п in ф.параметры:
                    if п in self.сводка_параметров[имя]:
                        continue
                    if self._утечка_парам_в_теле(ф.тело, {п}):
                        self.сводка_параметров[имя].add(п)
                        менялось = True

    def _утечка_парам_в_теле(self, тело, заражены: set) -> bool:
        """Утекает ли из множества заражённых имён хоть что-то в сток внутри тела."""
        for у in тело:
            if isinstance(у, (Пусть, Присвоить)):
                if self._выражение_утекает(у.значение, заражены):
                    return True
                if self._заражено(у.значение, заражены):
                    заражены.add(у.имя)
                else:
                    заражены.discard(у.имя)
            elif isinstance(у, Вернуть):
                if у.значение is not None and self._выражение_утекает(у.значение, заражены):
                    return True
            elif isinstance(у, Если):
                if self._выражение_утекает(у.условие, заражены):
                    return True
                ветка_а = set(заражены)
                ветка_б = set(заражены)
                if self._утечка_парам_в_теле(у.тогда, ветка_а):
                    return True
                if self._утечка_парам_в_теле(у.иначе, ветка_б):
                    return True
                заражены |= ветка_а | ветка_б
            elif isinstance(у, Пока):
                # Условие может само содержать сток.
                if self._выражение_утекает(у.условие, заражены):
                    return True
                # Цикл может не выполниться ни разу: заражение только ДОБАВЛЯЕМ
                # (тело анализируем на копии и объединяем), иначе теряем taint
                # параметра для стока ПОСЛЕ цикла.
                while True:
                    до = len(заражены)
                    тело_зар = set(заражены)
                    if self._утечка_парам_в_теле(у.тело, тело_зар):
                        return True
                    if self._выражение_утекает(у.условие, тело_зар):
                        return True
                    заражены |= тело_зар
                    if len(заражены) == до:
                        break
            else:
                if self._выражение_утекает(у, заражены):
                    return True
        return False

    def _выражение_утекает(self, в, заражены: set) -> bool:
        """Содержит ли выражение сток (прямой ИЛИ транзитивный) с заражённым аргументом."""
        if в is None or isinstance(в, (Число, Строка, Имя)):
            return False
        if isinstance(в, Бинарный):
            return (self._выражение_утекает(в.слева, заражены)
                    or self._выражение_утекает(в.справа, заражены))
        if isinstance(в, Вызов):
            if в.имя in СТОКИ:
                if any(self._заражено(а, заражены) for а in в.аргументы):
                    return True
            else:
                цель = self.функции.get(в.имя)
                if цель:
                    утечки = self.сводка_параметров.get(в.имя, set())
                    for i, а in enumerate(в.аргументы):
                        if (i < len(цель.параметры)
                                and цель.параметры[i] in утечки
                                and self._заражено(а, заражены)):
                            return True
            return any(self._выражение_утекает(а, заражены) for а in в.аргументы)
        return False

    def _проверить_стоки(self, в, заражены: set):
        """Ищет вызовы стоков и проверяет, что их аргументы не заражены."""
        if в is None:
            return
        if isinstance(в, Вызов):
            if в.имя in СТОКИ:
                for арг in в.аргументы:
                    if self._заражено(арг, заражены):
                        raise ЭтическаяОшибка(
                            f"УТЕЧКА ДАННЫХ (строка {в.строка}): личные данные "
                            f"уходят через сток '{в.имя}' без очистки. "
                            f"Оберните данные в санитайзер "
                            f"({' / '.join(sorted(САНИТАЙЗЕРЫ))}).")
            else:
                # Межпроцедурная проверка: заражённый аргумент уходит в параметр,
                # который внутри вызываемой функции утекает в сток.
                цель = self.функции.get(в.имя)
                if цель:
                    утечки = self.сводка_параметров.get(в.имя, set())
                    for i, арг in enumerate(в.аргументы):
                        if (i < len(цель.параметры)
                                and цель.параметры[i] in утечки
                                and self._заражено(арг, заражены)):
                            raise ЭтическаяОшибка(
                                f"УТЕЧКА ДАННЫХ (строка {в.строка}): личные данные "
                                f"передаются в '{в.имя}' через параметр "
                                f"'{цель.параметры[i]}', который внутри уходит в сток. "
                                f"Оберните данные в санитайзер "
                                f"({' / '.join(sorted(САНИТАЙЗЕРЫ))}).")
            for арг in в.аргументы:
                self._проверить_стоки(арг, заражены)
        elif isinstance(в, Бинарный):
            self._проверить_стоки(в.слева, заражены)
            self._проверить_стоки(в.справа, заражены)

    def _заражено(self, в, заражены: set) -> bool:
        """Заражено ли выражение хотя бы частично?"""
        if isinstance(в, (Число, Строка)):
            return False
        if isinstance(в, Имя):
            return в.имя in заражены
        if isinstance(в, Бинарный):
            return self._заражено(в.слева, заражены) or self._заражено(в.справа, заражены)
        if isinstance(в, Вызов):
            if в.имя in САНИТАЙЗЕРЫ:
                return False                      # результат санитайзера чист
            if в.имя in ИСТОЧНИКИ:
                return True                       # источник личных данных
            # пользовательская функция, возвращающая заражение (по сводке)
            if getattr(self, "сводка_возврата", {}).get(в.имя, False):
                return True
            # иначе заражён, если заражён любой аргумент (passthrough)
            return any(self._заражено(а, заражены) for а in в.аргументы)
        return False

    # --- вспомогательное: собрать все вызовы внутри утверждения ---
    def _все_вызовы_в(self, у):
        out = []

        def обойти_выр(в):
            if isinstance(в, Вызов):
                out.append(в)
                for а in в.аргументы:
                    обойти_выр(а)
            elif isinstance(в, Бинарный):
                обойти_выр(в.слева); обойти_выр(в.справа)

        def обойти_утв(s):
            if isinstance(s, (Пусть, Присвоить, Вернуть)):
                if getattr(s, "значение", None) is not None:
                    обойти_выр(s.значение)
            elif isinstance(s, Если):
                обойти_выр(s.условие)
                for x in s.тогда: обойти_утв(x)
                for x in s.иначе: обойти_утв(x)
            elif isinstance(s, Пока):
                обойти_выр(s.условие)
                for x in s.тело: обойти_утв(x)
            else:
                обойти_выр(s)

        обойти_утв(у)
        return out
