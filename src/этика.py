# -*- coding: utf-8 -*-
"""Этический анализатор YadroLang - закон на уровне компиляции.

Двухуровневая модель:
  1. Мандаты (capabilities): опасный API доступен только при явном мандате,
     транзитивно прокинутом до точки входа.
  2. Taint analysis: 'заражённые' данные не должны достигать стока без очистки.
"""
from src.синтаксис import Программа, Если, Пока, Вызов, Бинарный, Вернуть, Пусть, Присвоить


class ЭтическаяОшибка(Exception):
    ...


ОПАСНЫЕ_СТОКИ = {
    "сеть.отправить": "ДоступСети",
    "файл.записать": "ЗаписьДиска",
    "железо.прямой": "ПрямойДоступЖелезо",
    "модель.автономно": "АвтономноеДействие",
}
ТРЕБУЮТ_ОЧИСТКИ = {"сеть.отправить", "файл.записать"}
УЗЛЫ_ОЧИСТКИ = {"анонимизировать", "согласие_получено", "проверка_безопасности"}


class ЭтическийАнализатор:
    def __init__(self):
        self.мандаты = set()
        self.очищено = set()

    def проверить(self, прог: Программа):
        for ф in прог.функции:
            self.мандаты = set(ф.мандаты)
            self.очищено = set()
            for у in ф.тело:
                self._утв(у, ф)

    def _утв(self, у, ф):
        if isinstance(у, Если):
            for с in у.тогда:
                self._утв(с, ф)
            for с in у.иначе:
                self._утв(с, ф)
        elif isinstance(у, Пока):
            for с in у.тело:
                self._утв(с, ф)
        elif isinstance(у, (Вернуть, Пусть, Присвоить)):
            if getattr(у, "значение", None) is not None:
                self._выр(у.значение, ф)
        else:
            self._выр(у, ф)

    def _выр(self, в, ф):
        if isinstance(в, Вызов):
            for a in в.аргументы:
                self._выр(a, ф)
            if в.имя in УЗЛЫ_ОЧИСТКИ:
                self.очищено.add("*")
            if в.имя in ОПАСНЫЕ_СТОКИ:
                нужен = ОПАСНЫЕ_СТОКИ[в.имя]
                if нужен not in self.мандаты:
                    raise ЭтическаяОшибка(
                        f"ЗАКОН НАРУШЕН (строка {в.строка}): вызов '{в.имя}' требует "
                        f"мандат [{нужен}], которого нет у функции '{ф.имя}'.")
                if в.имя in ТРЕБУЮТ_ОЧИСТКИ and "*" not in self.очищено:
                    raise ЭтическаяОшибка(
                        f"ЗАКОН НАРУШЕН (строка {в.строка}): данные уходят через "
                        f"'{в.имя}' без проверки согласия/анонимизации.")
        elif isinstance(в, Бинарный):
            self._выр(в.слева, ф)
            self._выр(в.справа, ф)
