class ЭтическаяОшибка(Exception):
    ...


class ЗаписьАудита:
    """Одна запись в аудит-трейле потоков данных."""
    __slots__ = ("источник", "метка", "путь", "сток", "строка", "статус", "деталь")

    def __init__(self, источник, метка, путь, сток, строка, статус, деталь=""):
        self.источник = источник
        self.метка = метка
        self.путь = путь
        self.сток = сток
        self.строка = строка
        self.статус = статус     # "БЛОК" | "САНИТАЙЗ" | "НЕЯВНЫЙ_ПОТОК"
        self.деталь = деталь

    def __repr__(self):
        return (f"[{self.статус}] {self.метка}: {self.источник} -> "
                f"{' -> '.join(self.путь)} -> {self.сток} (строка {self.строка})"
                f"{': ' + self.деталь if self.деталь else ''}")


class ЭтическийАнализатор:
    def __init__(self):
        self.функции = {}
        self.аудит_трейл = []

    def проверить(self, прог: Программа):
        self.функции = {ф.имя: ф for ф in прог.функции}
        self.аудит_трейл = []
        self._вычислить_сводки_возврата()
        self._вычислить_сводки_параметров()
        for ф in прог.функции:
            self._мандаты(ф)
            self._taint(ф)
        return self.аудит_трейл

    # -----------------------------------------------------------------------
    # Сводки возвратов (фикспойнт)
    # -----------------------------------------------------------------------
    def _вычислить_сводки_возврата(self):
        self.сводка_возврата = {имя: False for имя in self.функции}
        while True:
            изменилось = False
            for имя, ф in self.функции.items():
                if self.сводка_возврата[имя]:
                    continue
                if self._тело_возвращает_заражение(ф.тело, set()):
                    self.сводка_возврата[имя] = True
                    изменилось = True
            if not изменилось:
                break

    def _тело_возвращает_заражение(self, тело, заражены: set) -> bool:
        возвр = False
        for у in тело:
            if isinstance(у, (Пусть, Присвоить)):
                if self._заражено(у.значение, заражены):
                    заражены.add(у.имя)
                else:
                    заражены.discard(у.имя)
            elif isinstance(у, Вернуть):
                if у.значение is not None and self._заражено(у.значение, заражены):
                    возвр = True
            elif isinstance(у, Если):
                а = заражены.copy(); б = заражены.copy()
                возвр = self._тело_возвращает_заражение(у.тогда, а) or возвр
                возвр = self._тело_возвращает_заражение(у.иначе, б) or возвр
                заражены |= а | б
            elif isinstance(у, Пока):
                while True:
                    до = len(заражены)
                    возвр = self._тело_возвращает_заражение(у.тело, заражены) or возвр
                    if len(заражены) == до:
                        break
        return возвр

    # -----------------------------------------------------------------------
    # Уровень 1: Проверка мандатов (capabilities)
    # -----------------------------------------------------------------------
    def _мандаты(self, ф: Функция):
        for утв in ф.тело:
            for вызов in self._все_вызовы_в(утв):
                нужен = СТОКИ.get(вызов.имя)
                if нужен and нужен not in ф.мандаты:
                    self.аудит_трейл.append(ЗаписьАудита(
                        источник="Н/Д", метка="МАНДАТ", путь=[ф.имя],
                        сток=вызов.имя, строка=вызов.строка,
                        статус="БЛОК",
                        деталь=f"Отсутствует мандат [{нужен}]"))
                    raise ЭтическаяОшибка(
                        f"Функция '{ф.имя}' (строка {вызов.строка}) вызывает "
                        f"'{вызов.имя}', требующий мандата [{нужен}], "
                        f"но мандат не объявлен в сигнатуре. "
                        f"Добавьте: функ {ф.имя}(...) требует [{нужен}]")
                цель = self.функции.get(вызов.имя)
                if цель:
                    for м in цель.мандаты:
                        if м not in ф.мандаты:
                            self.аудит_трейл.append(ЗаписьАудита(
                                источник="Н/Д", метка="МАНДАТ", путь=[ф.имя, цель.имя],
                                сток=вызов.имя, строка=вызов.строка,
                                статус="БЛОК",
                                деталь=f"Транзитивный мандат [{м}] отсутствует"))
                            raise ЭтическаяОшибка(
                                f"Функция '{ф.имя}' (строка {вызов.строка}) "
                                f"вызывает '{цель.имя}', требующую [{м}], "
                                f"но сама не объявляет [{м}].")

    # -----------------------------------------------------------------------
    # Уровень 2: Явный taint-анализ (data-flow)
    # -----------------------------------------------------------------------
    def _taint(self, ф: Функция):
        заражены = set()
        метки = {}
        неявная_глубина = 0
        self._taint_тело(ф.тело, заражены, метки, неявная_глубина)

    def _taint_тело(self, тело, заражены, метки, неявная_глубина):
        for у in тело:
            self._taint_утв(у, заражены, метки, неявная_глубина)

    def _taint_утв(self, у, заражены: set, метки: dict, неявная_глубина: int):
        if isinstance(у, Пусть):
            self._проверить_стоки(у.значение, заражены, метки, неявная_глубина)
            if self._заражено(у.значение, заражены):
                заражены.add(у.имя)
                метки[у.имя] = self._получить_метки(у.значение, заражены, метки)
            else:
                заражены.discard(у.имя)
                метки.pop(у.имя, None)

        elif isinstance(у, Присвоить):
            self._проверить_стоки(у.значение, заражены, метки, неявная_глубина)
            if self._заражено(у.значение, заражены):
                заражены.add(у.имя)
                метки[у.имя] = self._получить_метки(у.значение, заражены, метки)
            else:
                заражены.discard(у.имя)
                метки.pop(у.имя, None)

        elif isinstance(у, Вернуть):
            self._проверить_стоки(у.значение, заражены, метки, неявная_глубина)

        elif isinstance(у, Если):
            self._проверить_стоки(у.условие, заражены, метки, неявная_глубина)
            усл_заражено = self._заражено(у.условие, заражены)
            дочерняя_глубина = неявная_глубина + 1 if усл_заражено else неявная_глубина

            вет = заражены.copy()
            вет_метки = dict(метки)
            self._taint_тело(у.тогда, вет, вет_метки, дочерняя_глубина)

            вет2 = заражены.copy()
            вет2_метки = dict(метки)
            self._taint_тело(у.иначе, вет2, вет2_метки, дочерняя_глубина)

            заражены |= (вет | вет2)
            for к in (вет_метки.keys() | вет2_метки.keys()):
                слияние = вет_метки.get(к, set()) | вет2_метки.get(к, set())
                if слияние:
                    метки[к] = слияние

        elif isinstance(у, Пока):
            self._проверить_стоки(у.условие, заражены, метки, неявная_глубина)
            усл_заражено = self._заражено(у.условие, заражены)
            дочерняя_глубина = неявная_глубина + 1 if усл_заражено else неявная_глубина
            while True:
                до = len(заражены)
                тело_зар = заражены.copy()
                тело_метки = dict(метки)
                self._taint_тело(у.тело, тело_зар, тело_метки, дочерняя_глубина)
                заражены |= тело_зар
                for к, з in тело_метки.items():
                    метки.setdefault(к, set()).update(з)
                if len(заражены) == до:
                    break
        else:
            self._проверить_стоки(у, заражены, метки, неявная_глубина)

    # -----------------------------------------------------------------------
    # Уровень 3: Детекция неявного потока (implicit flow)
    # -----------------------------------------------------------------------
    def _проверить_неявный_поток(self, вызов, неявная_глубина, метки):
        if неявная_глубина > 0 and вызов.имя in СТОКИ:
            метки_в_области = set()
            for мн in метки.values():
                метки_в_области |= мн
            текст_меток = ", ".join(sorted(метки_в_области)) if метки_в_области else "неизвестно"
            self.аудит_трейл.append(ЗаписьАудита(
                источник="неявное-условие", метка=текст_меток,
                путь=[f"глубина-ветвления-{неявная_глубина}"],
                сток=вызов.имя, строка=вызов.строка,
                статус="НЕЯВНЫЙ_ПОТОК",
                деталь=f"Сток '{вызов.имя}' вызывается внутри ветки, условие "
                       f"которой зависит от чувствительных данных. Информация "
                       f"может утечь через control-flow."))
            raise ЭтическаяОшибка(
                f"Неявный информационный поток (строка {вызов.строка}): "
                f"сток '{вызов.имя}' вызывается внутри ветки, условие которой "
                f"зависит от чувствительных данных ({текст_меток}). "
                f"Даже если аргумент не заражен напрямую, структура ветвления "
                f"выдает информацию о чувствительном значении. "
                f"Вынесите вызов стока за пределы зараженной ветки или "
                f"санитизируйте переменную условия.")

    # -----------------------------------------------------------------------
    # Отслеживание меток
    # -----------------------------------------------------------------------
    def _получить_метки(self, в, заражены: set, метки: dict) -> set:
        if isinstance(в, (Число, Строка)):
            return set()
        if isinstance(в, Имя):
            return метки.get(в.имя, set())
        if isinstance(в, Бинарный):
            return self._получить_метки(в.слева, заражены, метки) | \
                   self._получить_метки(в.справа, заражены, метки)
        if isinstance(в, Вызов):
            if в.имя in САНИТАЙЗЕРЫ and в.имя not in self.функции:
                return set()
            метка = ИСТОЧНИКИ.get(в.имя)
            if метка:
                return {метка}
            результат = set()
            for а in в.аргументы:
                результат |= self._получить_метки(а, заражены, метки)
            return результат
        return set()

    # -----------------------------------------------------------------------
    # Проверка стоков (с учетом неявного потока)
    # -----------------------------------------------------------------------
    def _проверить_стоки(self, в, заражены: set, метки: dict, неявная_глубина: int):
        if в is None:
            return
        if isinstance(в, Вызов):
            self._проверить_неявный_поток(в, неявная_глубина, метки)

            if в.имя in СТОКИ:
                for арг in в.аргументы:
                    if self._заражено(арг, заражены):
                        м = self._получить_метки(арг, заражены, метки)
                        текст_м = ", ".join(sorted(м)) if м else "чувствительные"
                        self.аудит_трейл.append(ЗаписьАудита(
                            источник="прямой", метка=текст_м,
                            путь=[], сток=в.имя, строка=в.строка,
                            статус="БЛОК",
                            деталь=f"Зараженные данные ({текст_м}) утекают в сток"))
                        raise ЭтическаяОшибка(
                            f"Утечка данных (строка {в.строка}): данные типа {текст_м} "
                            f"достигают стока '{в.имя}' без санитизации. "
                            f"Оберните данные в санитайзер "
                            f"({' / '.join(sorted(САНИТАЙЗЕРЫ))}).")
            else:
                цель = self.функции.get(в.имя)
                if цель:
                    утечки = self.сводка_параметров.get(в.имя, set())
                    for и, арг in enumerate(в.аргументы):
                        if (и < len(цель.параметры)
                                and цель.параметры[и] in утечки
                                and self._заражено(арг, заражены)):
                            м = self._получить_метки(арг, заражены, метки)
                            текст_м = ", ".join(sorted(м)) if м else "чувствительные"
                            self.аудит_трейл.append(ЗаписьАудита(
                                источник="межпроцедурный", метка=текст_м,
                                путь=[в.имя, цель.параметры[и]],
                                сток="транзитивный", строка=в.строка,
                                статус="БЛОК",
                                деталь=f"Зараженный аргумент утекает через параметр '{цель.параметры[и]}'"))
                            raise ЭтическаяОшибка(
                                f"Утечка данных (строка {в.строка}): данные типа {текст_м} "
                                f"передаются в '{в.имя}' через параметр "
                                f"'{цель.параметры[и]}', который утекает в сток. "
                                f"Оберните данные в санитайзер "
                                f"({' / '.join(sorted(САНИТАЙЗЕРЫ))}).")
            for арг in в.аргументы:
                self._проверить_стоки(арг, заражены, метки, неявная_глубина)
        elif isinstance(в, Бинарный):
            self._проверить_стоки(в.слева, заражены, метки, неявная_глубина)
            self._проверить_стоки(в.справа, заражены, метки, неявная_глубина)

    # -----------------------------------------------------------------------
    # Проверка заражения
    # -----------------------------------------------------------------------
    def _заражено(self, в, заражены: set) -> bool:
        if isinstance(в, (Число, Строка)):
            return False
        if isinstance(в, Имя):
            return в.имя in заражены
        if isinstance(в, Бинарный):
            return self._заражено(в.слева, заражены) or self._заражено(в.справа, заражены)
        if isinstance(в, Вызов):
            if в.имя in САНИТАЙЗЕРЫ and в.имя not in self.функции:
                return False
            if в.имя in ИСТОЧНИКИ:
                return True
            if getattr(self, "сводка_возврата", {}).get(в.имя, False):
                return True
            return any(self._заражено(а, заражены) for а in в.аргументы)
        return False

    # -----------------------------------------------------------------------
    # Сводки параметров (фикспойнт)
    # -----------------------------------------------------------------------
    def _вычислить_сводки_параметров(self):
        self.сводка_параметров = {имя: set() for имя in self.функции}
        изменилось = True
        while изменилось:
            изменилось = False
            for имя, ф in self.функции.items():
                for п in ф.параметры:
                    if п in self.сводка_параметров[имя]:
                        continue
                    if self._утечка_парам_в_теле(ф.тело, {п}):
                        self.сводка_параметров[имя].add(п)
                        изменилось = True

    def _утечка_парам_в_теле(self, тело, заражены: set) -> bool:
        for у in тело:
            if isinstance(у, (Пусть, Присвоить)):
                if self._выражение_утекает(у.значение, заражены):
                    return True
                if self._заражено(у.значение, заражены):
                    заражены.add(у.имя)
                else:
                    заражены.discard(у.имя)
            elif isinstance(у, Вернуть):
                if у.значение is not None and self._выражение_утекает(у.значение, заражены):
                    return True
            elif isinstance(у, Если):
                if self._выражение_утекает(у.условие, заражены):
                    return True
                ветка_а = set(заражены)
                ветка_б = set(заражены)
                if self._утечка_парам_в_теле(у.тогда, ветка_а):
                    return True
                if self._утечка_парам_в_теле(у.иначе, ветка_б):
                    return True
                заражены |= ветка_а | ветка_б
            elif isinstance(у, Пока):
                if self._выражение_утекает(у.условие, заражены):
                    return True
                while True:
                    до = len(заражены)
                    тело_зар = set(заражены)
                    if self._утечка_парам_в_теле(у.тело, тело_зар):
                        return True
                    if self._выражение_утекает(у.условие, тело_зар):
                        return True
                    заражены |= тело_зар
                    if len(заражены) == до:
                        break
            else:
                if self._выражение_утекает(у, заражены):
                    return True
        return False

    def _выражение_утекает(self, в, заражены: set) -> bool:
        if в is None or isinstance(в, (Число, Строка, Имя)):
            return False
        if isinstance(в, Бинарный):
            return (self._выражение_утекает(в.слева, заражены)
                    or self._выражение_утекает(в.справа, заражены))
        if isinstance(в, Вызов):
            if в.имя in СТОКИ:
                if any(self._заражено(а, заражены) for а in в.аргументы):
                    return True
            else:
                цель = self.функции.get(в.имя)
                if цель:
                    утечки = self.сводка_параметров.get(в.имя, set())
                    for и, а in enumerate(в.аргументы):
                        if (и < len(цель.параметры)
                                and цель.параметры[и] in утечки
                                and self._заражено(а, заражены)):
                            return True
            return any(self._выражение_утекает(а, заражены) for а in в.аргументы)
        return False

    # -----------------------------------------------------------------------
    # Вспомогательное: собрать все вызовы внутри утверждения
    # -----------------------------------------------------------------------
    def _все_вызовы_в(self, у):
        out = []
        def обойти_выр(в):
            if isinstance(в, Вызов):
                out.append(в)
                for а in в.аргументы:
                    обойти_выр(а)
            elif isinstance(в, Бинарный):
                обойти_выр(в.слева); обойти_выр(в.справа)
        def обойти_утв(у):
            if isinstance(у, (Пусть, Присвоить, Вернуть)):
                if getattr(у, "значение", None) is not None:
                    обойти_выр(у.значение)
            elif isinstance(у, Если):
                обойти_выр(у.условие)
                for х in у.тогда: обойти_утв(х)
                for х in у.иначе: обойти_утв(х)
            elif isinstance(у, Пока):
                обойти_выр(у.условие)
                for х in у.тело: обойти_утв(х)
            else:
                обойти_выр(у)
        обойти_утв(у)
        return out

    # -----------------------------------------------------------------------
    # Генерация аудит-отчета
    # -----------------------------------------------------------------------
    def сгенерировать_аудит_отчет(self):
        отчет = []
        отчет.append("=" * 60)
        отчет.append("YADROLANG ЭТИЧЕСКИЙ АНАЛИЗАТОР - АУДИТ-ОТЧЕТ")
        отчет.append("=" * 60)
        блок = [з for з in self.аудит_трейл if з.статус == "БЛОК"]
        неявные = [з for з in self.аудит_трейл if з.статус == "НЕЯВНЫЙ_ПОТОК"]
        санитайз = [з for з in self.аудит_трейл if з.статус == "САНИТАЙЗ"]
        отчет.append(f"\nВсего находок: {len(self.аудит_трейл)}")
        отчет.append(f"  Заблокировано (явный поток):   {len(блок)}")
        отчет.append(f"  Заблокировано (неявный поток): {len(неявные)}")
        отчет.append(f"  Санитизировано (пропущено):    {len(санитайз)}")
        if self.аудит_трейл:
            отчет.append("\n--- Детальные находки ---")
            for запись in self.аудит_трейл:
                отчет.append(str(запись))
        отчет.append("\n" + "=" * 60)
        return "\n".join(отчет)
