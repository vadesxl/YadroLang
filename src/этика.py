"""Этический анализатор YadroLang v2.0 - закон на уровне компиляции.

Трехуровневая модель безопасности:

  1. МАНДАТЫ (capabilities). Опасный системный API (сеть, диск, БД)
     вызывается только из функции, в сигнатуре которой явно объявлен
     соответствующий мандат 'требует [...]'. Мандат проверяется транзитивно:
     если функция A вызывает B, требующую [ДоступСети], то A тоже обязана
     объявить его. Итог: все взаимодействие с миром видно в сигнатурах.
     Спрятать нельзя.

  2. ЯВНЫЙ TAINT-АНАЛИЗ (data-flow). Данные из источников личной информации
     помечаются как 'зараженные' с конкретной МЕТКОЙ (ПДн, Финансы, Здоровье).
     Заражение распространяется через присваивания, бинарные операции и
     вызовы функций. Если зараженное значение достигает стока (сеть/диск/лог)
     без прохождения через санитайзер - компиляция падает.

  3. НЕЯВНЫЙ ПОТОК (control-flow). Если условие ветвления зависит от
     зараженных данных, ЛЮБОЙ вызов стока внутри ветки блокируется - даже
     если аргумент сам по себе не заражен. Это предотвращает утечку информации
     через control-flow side-channels (например, отправка разных значений
     в зависимости от условия на персональных данных).

Закон до кода. Спрятать вредоносное поведение невозможно.
"""
