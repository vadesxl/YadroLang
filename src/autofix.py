# -*- coding: utf-8 -*-
"""Автоисправление утечек: подобрать обёртку и показать «было/стало».

Принцип безопасности: исправление предлагается ТОЛЬКО если переписанный код
реально проходит анализатор (компилируется без ЭтическойОшибки). Если проверка
не прошла — честно возвращаем «авто-починка невозможна», без ложных обещаний.
"""
import re
from src import этика_v21 as политика


def _выбрать_обёртку(метки):
    """Одна обёртка, покрывающая ВСЕ метки сразу (пересечение КОМПЛАЕНС)."""
    наборы = [политика.КОМПЛАЕНС.get(м, set()) for м in метки]
    if not наборы:
        return None
    общие = set(наборы[0]).intersection(*наборы[1:]) if len(наборы) > 1 else set(наборы[0])
    # Предпочитаем сильные и универсальные обёртки.
    for предпочтение in ("зашифровать", "токенизировать", "хэш", "маска",
                         "псевдонимизировать", "анонимизировать", "редактировать"):
        if предпочтение in общие:
            return предпочтение
    return sorted(общие)[0] if общие else None


def _обернуть_аргумент(строка, сток, обёртка):
    """В тексте строки заворачивает единственный аргумент вызова `сток(...)`.

    Возвращает (новая_строка, успех). Использует подсчёт скобок, чтобы корректно
    захватить вложенные вызовы вроде сеть.отправить(f(g(x))).
    """
    поз = строка.find(сток + "(")
    if поз < 0:
        return строка, False
    откр = поз + len(сток)
    глубина = 0
    for i in range(откр, len(строка)):
        if строка[i] == "(":
            глубина += 1
        elif строка[i] == ")":
            глубина -= 1
            if глубина == 0:
                аргумент = строка[откр + 1:i]
                if not аргумент.strip():
                    return строка, False
                # строка[i] — это закрывающая скобка самого стока, её сохраняем.
                новый = f"{строка[:откр + 1]}{обёртка}({аргумент}){строка[i:]}"
                return новый, True
    return строка, False


def предложить(исходник, диагностика):
    """По диагностике вернуть dict с планом фикса или None.

    dict: {обёртка, метки, строка, было, стало, новый_исходник, проверено}
    `проверено=True` только если переписанный код реально прошёл анализатор.
    """
    if not диагностика or диагностика.get("code") != "ЯДРО-Э2301":
        return None  # пока авто-чиним только прямые утечки данных
    сообщение = диагностика["message"]
    номер = диагностика["line"]
    метки = [м for м in политика.ВСЕ_МЕТКИ if re.search(rf"(?<!\w){re.escape(м)}(?!\w)", сообщение)]
    сток = re.search(r"стока? '([^']+)'", сообщение)
    if not метки or not сток:
        return None
    сток = сток.group(1)
    обёртка = _выбрать_обёртку(метки)
    if not обёртка:
        return None  # нет обёртки, покрывающей все метки — честно не чиним
    строки = исходник.splitlines()
    if not (1 <= номер <= len(строки)):
        return None
    было = строки[номер - 1]
    стало, ок = _обернуть_аргумент(было, сток, обёртка)
    if not ок:
        return None
    строки[номер - 1] = стало
    новый = "\n".join(строки)
    return {"обёртка": обёртка, "метки": метки, "строка": номер,
            "было": было, "стало": стало, "новый_исходник": новый,
            "проверено": _проверить(новый)}


def _проверить(исходник):
    """Проходит ли переписанный код анализатор без нарушения политики."""
    from src.main import компилировать
    from src.этика import ЭтическаяОшибка
    try:
        компилировать(исходник)
        return True
    except ЭтическаяОшибка:
        return False
    except Exception:
        return False  # синтаксис/типы сломались — фикс считаем ненадёжным
