# -*- coding: utf-8 -*-
"""Минимальная строгая система типов YadroLang."""
from src.синтаксис import (Вернуть, Пусть, Присвоить, Если, Пока, Число,
                           Строка, Имя, Бинарный, Вызов)

I64, БУЛЕВ, СТРОКА = "i64", "bool", "string"

class ОшибкаТипов(Exception):
 def __init__(self,код,сообщение,строка=0):self.код=код;self.строка=строка;super().__init__(f"[{код}] строка {строка}: {сообщение}")

class ПроверкаТипов:
 def __init__(self,программа,системные):
  self.программа=программа;self.функции={ф.имя:ф for ф in программа.функции};self.системные=set(системные)
  self.возвраты={имя:I64 for имя in self.функции};self.параметры={имя:[I64]*len(ф.параметры) for имя,ф in self.функции.items()}
 def проверить(self):
  self._символы()
  for _ in range(32):
   изменилось=False
   for функция in self.программа.функции:
    тип=self._функция(функция,False)
    if тип and тип!=self.возвраты[функция.имя]:self.возвраты[функция.имя]=тип;изменилось=True
   if not изменилось:break
  else:raise ОшибкаТипов("ЯДРО-Т2901","вывод типов возврата не сошёлся")
  for функция in self.программа.функции:self._функция(функция,True)
  return self
 def _символы(self):
  for функция in self.программа.функции:
   if функция.имя in {"main","printf"} or функция.имя.startswith("ext."):raise ОшибкаТипов("ЯДРО-Т2101",f"зарезервированный runtime-символ '{функция.имя}'",функция.строка)
 def _функция(self,функция,валидация):
  окружение={имя:I64 for имя in функция.параметры};типы,завершено=self._блок(функция.тело,окружение,валидация)
  if валидация and not завершено:raise ОшибкаТипов("ЯДРО-Т2204",f"не все пути функции '{функция.имя}' возвращают значение",функция.строка)
  if not типы:return I64
  if len(типы)!=1:raise ОшибкаТипов("ЯДРО-Т2203",f"несовместимые типы возврата: {sorted(типы)}",функция.строка)
  результат=next(iter(типы))
  if результат==СТРОКА:raise ОшибкаТипов("ЯДРО-Т2205","string ABI возврата пока не поддерживается",функция.строка)
  return результат
 def _блок(self,тело,окружение,валидация):
  возвраты=set();завершено=False
  for утверждение in тело:
   if завершено:
    if валидация:raise ОшибкаТипов("ЯДРО-Т2202","недостижимое утверждение",утверждение.строка)
    break
   if isinstance(утверждение,Пусть):
    тип=self._выражение(утверждение.значение,окружение)
    if тип==СТРОКА:raise ОшибкаТипов("ЯДРО-Т2305","строковые переменные пока не поддерживаются; печатайте литерал напрямую",утверждение.строка)
    окружение[утверждение.имя]=тип
   elif isinstance(утверждение,Присвоить):
    if утверждение.имя not in окружение:raise ОшибкаТипов("ЯДРО-Т2102",f"неизвестная переменная '{утверждение.имя}'",утверждение.строка)
    тип=self._выражение(утверждение.значение,окружение)
    if тип!=окружение[утверждение.имя]:raise ОшибкаТипов("ЯДРО-Т2302",f"нельзя присвоить {тип} переменной {окружение[утверждение.имя]}",утверждение.строка)
   elif isinstance(утверждение,Вернуть):возвраты.add(self._выражение(утверждение.значение,окружение));завершено=True
   elif isinstance(утверждение,Если):
    условие=self._выражение(утверждение.условие,окружение)
    if условие not in {БУЛЕВ,I64}:raise ОшибкаТипов("ЯДРО-Т2303",f"условие если должно быть bool или i64, получено {условие}",утверждение.строка)
    левое,правое=dict(окружение),dict(окружение);лвоз,лзав=self._блок(утверждение.тогда,левое,валидация);пвоз,пзав=self._блок(утверждение.иначе,правое,валидация);возвраты|=лвоз|пвоз
    for имя in set(левое)|set(правое):
     лт,пт=левое.get(имя),правое.get(имя)
     if лт and пт and лт!=пт:raise ОшибкаТипов("ЯДРО-Т2304",f"конфликт типа '{имя}': {лт} и {пт}",утверждение.строка)
     if лт==пт and лт:окружение[имя]=лт
    завершено=bool(утверждение.иначе) and лзав and пзав
   elif isinstance(утверждение,Пока):
    условие=self._выражение(утверждение.условие,окружение)
    if условие not in {БУЛЕВ,I64}:raise ОшибкаТипов("ЯДРО-Т2303",f"условие пока должно быть bool или i64, получено {условие}",утверждение.строка)
    типы,_=self._блок(утверждение.тело,dict(окружение),валидация);возвраты|=типы
   else:self._выражение(утверждение,окружение)
  return возвраты,завершено
 def _выражение(self,узел,окружение):
  if isinstance(узел,Число):return I64
  if isinstance(узел,Строка):return СТРОКА
  if isinstance(узел,Имя):
   if узел.имя not in окружение:raise ОшибкаТипов("ЯДРО-Т2102",f"неизвестная переменная '{узел.имя}'",узел.строка)
   return окружение[узел.имя]
  if isinstance(узел,Бинарный):
   слева,справа=self._выражение(узел.слева,окружение),self._выражение(узел.справа,окружение)
   if слева!=I64 or справа!=I64:raise ОшибкаТипов("ЯДРО-Т2301",f"оператор '{узел.оп}' требует i64, получено {слева} и {справа}",узел.строка)
   return БУЛЕВ if узел.оп in {">","<","=="} else I64
  if isinstance(узел,Вызов):
   аргументы=[self._выражение(а,окружение) for а in узел.аргументы]
   if узел.имя=="печать":return I64
   if узел.имя in self.функции:
    for индекс,(факт,ожид) in enumerate(zip(аргументы,self.параметры[узел.имя]),1):
     if факт!=ожид:raise ОшибкаТипов("ЯДРО-Т2402",f"аргумент {индекс} '{узел.имя}' ожидает {ожид}, получено {факт}",узел.строка)
    return self.возвраты[узел.имя]
   for факт in аргументы:
    if факт!=I64:raise ОшибкаТипов("ЯДРО-Т2403",f"системный API '{узел.имя}' принимает i64, получено {факт}",узел.строка)
   return I64
  raise ОшибкаТипов("ЯДРО-Т2999",f"невозможно вывести тип {type(узел).__name__}",getattr(узел,"строка",0))
