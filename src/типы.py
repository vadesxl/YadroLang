from src.синтаксис import Число,Строка,Булево,Имя,Бинарный,Вызов,Пусть,Присвоить,Вернуть,Если,Пока
I64,BOOL,STRING,UNKNOWN="i64","bool","string","unknown"
class ОшибкаТипов(RuntimeError):
 def __init__(self,с,строка=0,код="ЯДРО-Т2000"):self.код=код;super().__init__(f"[{код}] {с} (строка {строка})")
class ПроверкаТипов:
 МАКС=64
 def __init__(self,api):self.api=set(api)
 def проверить(self,программа):
  self.с={ф.имя:{"п":[UNKNOWN]*len(ф.параметры),"в":UNKNOWN} for ф in программа.функции}
  for _ in range(self.МАКС):
   до=repr(self.с)
   for ф in программа.функции:self._ф(ф)
   if repr(self.с)==до:break
  else:raise ОшибкаТипов("вывод типов не сошёлся",0,"ЯДРО-Т2099")
  for с in self.с.values():с["п"]=[I64 if x==UNKNOWN else x for x in с["п"]];с["в"]=I64 if с["в"]==UNKNOWN else с["в"]
  for ф in программа.функции:self._ф(ф);ф.выведенные_типы_параметров=list(self.с[ф.имя]["п"]);ф.выведенный_тип_возврата=self.с[ф.имя]["в"]
  return self.с
 def _слить(self,а,б,стр,контекст):
  if б==UNKNOWN:return а
  if а==UNKNOWN:return б
  if а!=б:raise ОшибкаТипов(f"{контекст}: ожидался {а}, получен {б}",стр,"ЯДРО-Т2002")
  return а
 def _ф(self,ф):
  с=self.с[ф.имя];окр=dict(zip(ф.параметры,с["п"]));воз=[];self._тело(ф.тело,окр,воз)
  for т,стр in воз:с["в"]=self._слить(с["в"],т,стр,f"тип возврата '{ф.имя}'")
 def _тело(self,тело,окр,воз):
  завершено=False
  for у in тело:
   if завершено:raise ОшибкаТипов("недостижимое утверждение после вернуть",у.строка,"ЯДРО-Т2006")
   if isinstance(у,Пусть):
    т=self._выр(у.значение,окр)
    if у.имя in окр:raise ОшибкаТипов(f"переменная '{у.имя}' уже объявлена",у.строка,"ЯДРО-Т2007")
    окр[у.имя]=т;у.выведенный_тип=т
   elif isinstance(у,Присвоить):
    if у.имя not in окр:raise ОшибкаТипов(f"неизвестная переменная '{у.имя}'",у.строка,"ЯДРО-Т2008")
    окр[у.имя]=self._слить(окр[у.имя],self._выр(у.значение,окр),у.строка,f"присваивание '{у.имя}'")
   elif isinstance(у,Вернуть):воз.append((self._выр(у.значение,окр),у.строка));завершено=True
   elif isinstance(у,Если):
    т=self._выр(у.условие,окр)
    if т not in (BOOL,I64,UNKNOWN):raise ОшибкаТипов("условие если должно быть bool или legacy i64",у.строка,"ЯДРО-Т2003")
    л,п=dict(окр),dict(окр);лв,пв=[],[];лз=self._тело(у.тогда,л,лв);пз=self._тело(у.иначе,п,пв) if у.иначе else False;воз.extend(лв+пв)
    for имя in окр:окр[имя]=self._слить(л.get(имя,окр[имя]),п.get(имя,окр[имя]),у.строка,f"ветка '{имя}'")
    завершено=bool(у.иначе) and лз and пз
   elif isinstance(у,Пока):
    т=self._выр(у.условие,окр)
    if т not in (BOOL,I64,UNKNOWN):raise ОшибкаТипов("условие пока должно быть bool или legacy i64",у.строка,"ЯДРО-Т2003")
    ц=dict(окр);вр=[];self._тело(у.тело,ц,вр);воз.extend(вр)
    for имя in окр:окр[имя]=self._слить(окр[имя],ц.get(имя,окр[имя]),у.строка,f"цикл '{имя}'")
   else:self._выр(у,окр)
  return завершено
 def _выр(self,у,окр):
  if isinstance(у,Число):р=I64
  elif isinstance(у,Строка):р=STRING
  elif isinstance(у,Булево):р=BOOL
  elif isinstance(у,Имя):
   if у.имя not in окр:raise ОшибкаТипов(f"неизвестная переменная '{у.имя}'",у.строка,"ЯДРО-Т2008")
   р=окр[у.имя]
  elif isinstance(у,Бинарный):
   л,п=self._выр(у.слева,окр),self._выр(у.справа,окр)
   if у.оп in ("+","-","*","/",">","<"):
    if л not in (I64,UNKNOWN) or п not in (I64,UNKNOWN):raise ОшибкаТипов(f"оператор '{у.оп}' требует i64",у.строка,"ЯДРО-Т2001")
    р=BOOL if у.оп in (">","<") else I64
   elif у.оп=="==":self._слить(л,п,у.строка,"операнды равенства");р=BOOL
   else:raise ОшибкаТипов(f"неизвестный оператор '{у.оп}'",у.строка)
  elif isinstance(у,Вызов):
   а=[self._выр(x,окр) for x in у.аргументы]
   if у.имя=="печать":р=I64
   elif у.имя in self.с:
    с=self.с[у.имя]
    for i,т in enumerate(а):с["п"][i]=self._слить(с["п"][i],т,у.строка,f"аргумент {i+1} '{у.имя}'")
    р=с["в"]
   elif у.имя in self.api:
    if any(т not in (I64,UNKNOWN) for т in а):raise ОшибкаТипов(f"системный API '{у.имя}' принимает только i64",у.строка,"ЯДРО-Т2004")
    р=I64
   else:raise ОшибкаТипов(f"неизвестная функция '{у.имя}'",у.строка,"ЯДРО-Т2009")
  else:raise ОшибкаТипов(f"неподдерживаемое выражение {type(у).__name__}",getattr(у,"строка",0))
  у.выведенный_тип=р;return р
