# -*- coding: utf-8 -*-
"""Минимальная строгая система типов YadroLang: i64, bool, string."""
from src.синтаксис import (Число, Строка, Булево, Имя, Бинарный, Вызов,
                           Пусть, Присвоить, Вернуть, Если, Пока)
I64, BOOL, STRING, UNKNOWN = "i64", "bool", "string", "unknown"

class ОшибкаТипов(RuntimeError):
    def __init__(self, сообщение, строка=0, код="ЯДРО-Т2000"):
        self.код=код; super().__init__(f"[{код}] {сообщение} (строка {строка})")

class ПроверкаТипов:
    МАКС=64
    def __init__(self, api): self.api=set(api); self.сигнатуры={}
    def проверить(self, программа):
        self.сигнатуры={ф.имя:{"параметры":[UNKNOWN]*len(ф.параметры),"возврат":UNKNOWN} for ф in программа.функции}
        for _ in range(self.МАКС):
            до=repr(self.сигнатуры)
            for ф in программа.функции: self._функция(ф,True)
            if repr(self.сигнатуры)==до: break
        else: raise ОшибкаТипов("вывод типов не сошёлся",0,"ЯДРО-Т2099")
        for с in self.сигнатуры.values():
            с["параметры"]=[I64 if т==UNKNOWN else т for т in с["параметры"]]
            if с["возврат"]==UNKNOWN: с["возврат"]=I64
        for ф in программа.функции:
            self._функция(ф,False); ф.выведенные_типы_параметров=list(self.сигнатуры[ф.имя]["параметры"]); ф.выведенный_тип_возврата=self.сигнатуры[ф.имя]["возврат"]
        return self.сигнатуры
    def _слить(self,старый,новый,строка,контекст):
        if новый==UNKNOWN:return старый
        if старый==UNKNOWN:return новый
        if старый!=новый: raise ОшибкаТипов(f"{контекст}: ожидался {старый}, получен {новый}",строка,"ЯДРО-Т2002")
        return старый
    def _функция(self,ф,infer):
        с=self.сигнатуры[ф.имя]; окружение=dict(zip(ф.параметры,с["параметры"])); возвраты=[]; self._тело(ф.тело,окружение,возвраты,infer)
        for тип,строка in возвраты: с["возврат"]=self._слить(с["возврат"],тип,строка,f"тип возврата '{ф.имя}'")
    def _тело(self,тело,окружение,возвраты,infer):
        завершено=False
        for у in тело:
            if завершено: raise ОшибкаТипов("недостижимое утверждение после вернуть",у.строка,"ЯДРО-Т2006")
            if isinstance(у,Пусть):
                тип=self._выражение(у.значение,окружение,infer)
                if у.имя in окружение: raise ОшибкаТипов(f"переменная '{у.имя}' уже объявлена",у.строка,"ЯДРО-Т2007")
                окружение[у.имя]=тип; у.выведенный_тип=тип
            elif isinstance(у,Присвоить):
                if у.имя not in окружение: raise ОшибкаТипов(f"неизвестная переменная '{у.имя}'",у.строка,"ЯДРО-Т2008")
                окружение[у.имя]=self._слить(окружение[у.имя],self._выражение(у.значение,окружение,infer),у.строка,f"присваивание '{у.имя}'")
            elif isinstance(у,Вернуть): возвраты.append((self._выражение(у.значение,окружение,infer),у.строка)); завершено=True
            elif isinstance(у,Если):
                тип=self._выражение(у.условие,окружение,infer)
                if тип not in (BOOL,I64,UNKNOWN): raise ОшибкаТипов("условие если должно быть bool или legacy i64",у.строка,"ЯДРО-Т2003")
                л,п=dict(окружение),dict(окружение); лв,пв=[],[]; лз=self._тело(у.тогда,л,лв,infer); пз=self._тело(у.иначе,п,пв,infer) if у.иначе else False; возвраты.extend(лв+пв)
                for имя in окружение: окружение[имя]=self._слить(л.get(имя,окружение[имя]),п.get(имя,окружение[имя]),у.строка,f"ветка '{имя}'")
                завершено=bool(у.иначе) and лз and пз
            elif isinstance(у,Пока):
                тип=self._выражение(у.условие,окружение,infer)
                if тип not in (BOOL,I64,UNKNOWN): raise ОшибкаТипов("условие пока должно быть bool или legacy i64",у.строка,"ЯДРО-Т2003")
                цикл=dict(окружение); вр=[]; self._тело(у.тело,цикл,вр,infer); возвраты.extend(вр)
                for имя in окружение: окружение[имя]=self._слить(окружение[имя],цикл.get(имя,окружение[имя]),у.строка,f"цикл '{имя}'")
            else:self._выражение(у,окружение,infer)
        return завершено
    def _выражение(self,узел,окружение,infer):
        if isinstance(узел,Число):рез=I64
        elif isinstance(узел,Строка):рез=STRING
        elif isinstance(узел,Булево):рез=BOOL
        elif isinstance(узел,Имя):
            if узел.имя not in окружение: raise ОшибкаТипов(f"неизвестная переменная '{узел.имя}'",узел.строка,"ЯДРО-Т2008")
            рез=окружение[узел.имя]
        elif isinstance(узел,Бинарный):
            л,п=self._выражение(узел.слева,окружение,infer),self._выражение(узел.справа,окружение,infer)
            if узел.оп in ("+","-","*","/",">","<"):
                if л not in (I64,UNKNOWN) or п not in (I64,UNKNOWN): raise ОшибкаТипов(f"оператор '{узел.оп}' требует i64",узел.строка,"ЯДРО-Т2001")
                рез=BOOL if узел.оп in (">","<") else I64
            elif узел.оп=="==":
                self._слить(л,п,узел.строка,"операнды равенства")
                if STRING in (л,п): raise ОшибкаТипов("равенство строк не реализовано",узел.строка,"ЯДРО-Т2005")
                рез=BOOL
            else: raise ОшибкаТипов(f"неизвестный оператор '{узел.оп}'",узел.строка)
        elif isinstance(узел,Вызов):
            арг=[self._выражение(a,окружение,infer) for a in узел.аргументы]
            if узел.имя=="печать":рез=I64
            elif узел.имя in self.сигнатуры:
                с=self.сигнатуры[узел.имя]
                for i,тип in enumerate(арг):с["параметры"][i]=self._слить(с["параметры"][i],тип,узел.строка,f"аргумент {i+1} '{узел.имя}'")
                рез=с["возврат"]
            elif узел.имя in self.api:
                if any(т not in (I64,UNKNOWN) for т in арг): raise ОшибкаТипов(f"системный API '{узел.имя}' принимает только i64",узел.строка,"ЯДРО-Т2004")
                рез=I64
            else: raise ОшибкаТипов(f"неизвестная функция '{узел.имя}'",узел.строка,"ЯДРО-Т2009")
        else: raise ОшибкаТипов(f"неподдерживаемое выражение {type(узел).__name__}",getattr(узел,"строка",0))
        узел.выведенный_тип=рез; return рез
